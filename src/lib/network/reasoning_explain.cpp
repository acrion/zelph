    // A rule in force, parsed once and retained across successive explanations
    // as long as the rules remain unchanged (see Reasoning::explain). In force
    // signifies what forward evaluators interpret it to mean: a `=>` fact that
    // no other statement merely mentions (Zelph::is_mentioned). A mentioned
    // rule -- the template contained within a rule generator, or a rule that
    // some statement refers to -- never fires, thus providing no
    // justification. Enumerated as a rule, a generator's template, with its
    // predicate being a variable, unified with each fact: it explained the
    // derivation of the logic.md ontology example backwards and announced
    // second justifications that were nonexistent. The list keeps the order in
    // which get_left(core.Causes) yields the rules, since this sequence
    // determines which instantiation the search meets first.
    struct Reasoning::ExplainRules
    {
        // Where Unification starts on a positive condition: its subject,
        // otherwise its first object, otherwise every fact associated with
        // its predicate (refer to scan_estimate); and the variables that
        // binding it leaves bound.
        struct Shape
        {
            Node              subject{0};
            Node              object{0};
            Node              relation{0};
            std::vector<Node> variables;
        };

        // A consequence, whether it is itself a rule, and its predicate when
        // that is a plain node: seed-mode Unification matches it only against
        // a fact bearing that predicate.
        //
        // A firing replaces a collection of the rule's own text with its
        // term, meaning the fact it derives holds a different collection
        // than the consequence does, and matching the two through identity
        // would fail to locate a rule for the fact. `containers` holds the
        // stand-ins the consequence is matched against (firing_stand_ins): a
        // bucket represents its term, and a collection that the firing gives
        // a term of its own represents any term, which one becoming known
        // solely through the bindings of the whole rule;
        // Reasoning::existing_consequence determines this after the join.
        struct Head
        {
            Node        consequence{0};
            bool        produces_rule{false};
            Node        predicate{0};
            PatternInfo pattern; // what Unification reads from the consequence, read once
            StandIns    containers;
        };

        struct Rule
        {
            Node                     rule{0};
            Node                     condition{0}; // the condition part: a single pattern, or the conjunction set
            adjacency_set            consequences;
            std::vector<Head>        heads;
            std::vector<Node>        positive;
            std::vector<Shape>       shapes;   // per positive condition
            std::vector<PatternInfo> patterns; // per positive condition
            std::vector<Node>        negative;
            std::vector<PatternInfo> negative_patterns;
            std::vector<Node>        guards;
            std::vector<Node>        closures;
            std::vector<Node>        negated_closures;
            bool                     neural{false};
        };

        std::vector<Rule> rules;

        // What the list was read from: every node get_left(core.Causes)
        // yields, in order, with its edge count and the position of its rule
        // within `rules` (none: not a rule in force). A rule that comes or
        // vanishes alters the first item, while a statement that comes to
        // mention a rule or stops mentioning it changes the second.
        //
        // The way a rule reads depends not only on the rule node but also on
        // tags attached to its condition and to the elements of a conjunction.
        // A ground condition is shared by content with the asserted fact and
        // with each rule that writes it; a subsequent rule that writes it
        // negated tags it for all of them. These nodes, along with their
        // connecting edges, are watched, as are the collections within a
        // consequence that a firing replaces by a term of its own
        // (Head::containers), whose kind is determined by examining their
        // members.
        //
        // The number of edges says that a node remains unaltered only while
        // no removal has affected it: an addition increases the count, yet a
        // removal followed by an addition brings it back to the prior state
        // -- two statements about a ground condition that has been pruned, a
        // rule that negates it written, and the rule was adopted along with
        // its positive condition. The list names each node it was read from
        // to the graph (Zelph::watch_removals), and a node that has undergone
        // a removal since is re-read; a removal elsewhere imposes no cost,
        // nor does a prune incur any expense for it. `epoch` belongs to the
        // graph, advancing with every load, one that merges a file into the
        // session as well (Network::note_load).
        struct Source
        {
            Node                                      node{0};
            std::size_t                               edges{0};
            std::size_t                               rule{std::numeric_limits<std::size_t>::max()};
            std::vector<std::pair<Node, std::size_t>> watched;
        };
        std::vector<Source> read_from;
        Node                nn_pred{0};
        Node                closure_pred{0};
        std::uint64_t       epoch{0};

        // The predicates some rule concludes; any of them, when a
        // consequence involves a variable predicate (see walk_premises).
        std::unordered_set<Node> concluded;
        bool                     concludes_any{false};
    };

    namespace
    {
        using RuleInForce = Reasoning::ExplainRules::Rule;

        // How a proof stands, in the order the search prefers: not grounded
        // (each instantiation currently found depends on a component member
        // that is still being searched), founded (grounded, yet at least one
        // subordinate leaf is an "asserted; no derivation found" leaf),
        // clean (each leaf qualifies as an axiom or is the depth limit).
        enum class Grade
        {
            Ungrounded,
            Founded,
            Clean
        };

        constexpr std::size_t none = std::numeric_limits<std::size_t>::max();

        // The walk taken for a single path condition of an instantiation:
        // the condition (an index into Candidate::walked), the facts it
        // steps over, the number of walks previously executed for it, and
        // the facts being searched that earlier walks met, around which this
        // one was executed (see rewalk).
        struct Walk
        {
            std::size_t       condition{0};
            std::vector<Node> edges;
            std::size_t       generation{0};
            std::vector<Node> around;
        };

        // A single instantiation of a rule regarding a fact: all that a
        // proof step shows, along with what the component's fixpoint
        // needs to assign a grade to it.
        struct Candidate
        {
            Node                                    rule{0};
            Variables                               bindings;
            std::vector<Node>                       walked;
            std::vector<Node>                       absent;
            std::vector<Node>                       facts;                 // the premises the join discovered
            std::vector<std::shared_ptr<ProofNode>> premises;              // their proofs
            std::vector<bool>                       member;                // The premise within a component that is still being searched
            std::vector<Node>                       rests_on;              // facts being searched for which a reused premise holds an earlier result
            Grade                                   settled{Grade::Clean}; // the minimum grade among the premises that are not members
            std::size_t                             shown{none};           // the premises the step shows; the rest are edges its walks step over
            std::vector<std::size_t>                walk_of;               // for each premise, the path condition whose walk steps over it; none if it is shown
            std::vector<Walk>                       walks;
        };

        // What information the search holds
        // regarding a single fact.
        struct Entry
        {
            std::shared_ptr<ProofNode> proof;
            std::size_t                index{0};                 // Tarjan: the sequence by which facts were entered
            std::size_t                lowlink{0};               // Tarjan: the smallest index attained via open premises
            std::size_t                depth{0};                 // the depth of the most recent search, the least deep so far
            std::size_t                searches{0};              // the frequency with which the fact has been searched
            Grade                      grade{Grade::Ungrounded}; // the optimal instantiation lacking open premises; definitive upon completion
            bool                       complete{false};
            bool                       truncated{false}; // the outcome depends on the depth limit
            bool                       unified{false};   // a rule consequence unified with the fact
            Node                       predicate{0};
            std::vector<Candidate>     candidates; // the instantiations created; the component chooses from among them
        };

        // The state of a single explanation. It expands with the facts the
        // search enters, not with the graph, and it is freed when
        // explain() returns.
        struct ExplainContext
        {
            Zelph*           z{nullptr};           // mutable view for the Unification API; never used to write
            const Reasoning* engine{nullptr};      // the identical engine, for existing_rule
            Node             nn_pred{0};           // node named "nn" in lang "zelph" (approx conditions); 0 = inactive
            Node             closure_pred{0};      // "closure" (path conditions); 0 = inactive
            Node             closure_zero_plus{0}; // "zero-or-more" -- the reflexive variant
            Node             root{0};
            std::size_t      max_depth{0};

            std::span<const RuleInForce>    rules;
            std::unordered_map<Node, Entry> table;
            std::vector<Node>               stack; // Tarjan's stack: has been entered, component still incomplete
            std::size_t                     next_index{0};
            std::unordered_map<Node, bool>  concludes; // if a rule consequence matches the fact

            // The facts of each predicate on Tarjan's stack: a walk over a
            // path condition may run over them (refer to walk_premises).
            // Retained throughout stack modifications, because gathering
            // them during each walk would incur a cost proportional to the
            // square of a chain's length.
            std::unordered_map<Node, adjacency_set> open_by_predicate;

            // What the path conditions' walks omit, as the forward pass
            // does (Zelph::unasserted_snapshot), taken once; and what the
            // rules in force conclude.
            std::shared_ptr<const adjacency_set> unasserted;
            const Reasoning::ExplainRules*       in_force{nullptr};

            // Outcomes contingent upon the depth limit: complete proofs and
            // the leaves cut at the limit (status Truncated), with the depth
            // at which they were discovered. Each is held here, ensuring its
            // address cannot be transferred to another node once nothing else
            // holds it. A fact that one of them holds an earlier outcome for
            // -- either a leaf cut at the limit or a result rediscovered from
            // above -- is listed in `superseded`, while `open_superseded`
            // tallies how many of these are currently being searched (see
            // held).
            struct Limited
            {
                std::shared_ptr<ProofNode> proof;
                std::size_t                depth{0};
            };
            std::unordered_map<const ProofNode*, Limited> limited;
            std::unordered_set<Node>                      superseded;
            std::size_t                                   open_superseded{0};

            // When the levels of a finished tree are restored (see
            // restore_levels): the facts located above the fact being
            // searched once more, which the new result must not depend upon,
            // and which complete proofs hold one of them.
            std::unordered_set<Node>                                                          above;
            std::unordered_map<const ProofNode*, std::pair<std::shared_ptr<ProofNode>, bool>> holds_above;

            // For each subject and predicate, the highest number of objects
            // that any of their associated facts carries (see
            // resolve_premise).
            std::unordered_map<Node, std::unordered_map<Node, std::size_t>> widest;
            bool                                                            more{false}; // the root has a further justification found so far
            Reasoning::ExplainCounts                                        counts;

            // The work done (see charge); the work the search for the root's
            // proof may do, 0 if no bound applies (see Reasoning::explain);
            // the work at which `spent` decides -- the budget up to when the
            // root holds a clean proof, the bound of the annotation
            // thereafter; and the index of the first fact entered for the
            // root's current further instantiation (see abandon_alternative).
            std::size_t work{0};
            std::size_t budget{0};
            std::size_t work_limit{std::numeric_limits<std::size_t>::max()};
            bool        root_clean{false};
            std::size_t alternative_from{0};
        };

        // Thrown when the search for the root's proof has exhausted the
        // work permitted by its budget.
        struct BudgetSpent
        {
        };

        // Thrown when the root, which holds a clean proof, has done the work
        // permitted by its bound on a further justification (see
        // annotation_floor).
        struct AnnotationSpent
        {
        };

        // How much work the search to find the complete proof may expend
        // beneath a depth limit before the search within the limit takes
        // over (see Reasoning::explain).
        constexpr std::size_t default_explain_budget = 80000;

        // When the root holds a clean proof, it may seek a further
        // justification provided no more work has been done since the proof
        // was completed than the amount the proof required, plus the value of
        // `annotation_floor`: the annotation builds every instantiation it
        // judges, and judging alternatives that run back to the root via an
        // extended chain incurs a cost thousands of times greater than the
        // original proof -- handling a hundred such chains, each with a
        // hundred facts, took 80 s next to a two-step proof. A justification
        // discovered at a later stage is not reported; this is the price of
        // the bound, and it never results in a false annotation.
        constexpr std::size_t annotation_floor = 5000;

        // The work at which the search decides, after having accomplished
        // this much.
        void spent(ExplainContext& ctx)
        {
            if (ctx.root_clean) throw AnnotationSpent{};
            if (ctx.budget != 0) throw BudgetSpent{};
            ctx.work_limit = std::numeric_limits<std::size_t>::max();
        }

        // The search measures its operations in units of roughly equal cost:
        // a fact entered, a match enumerated, a premise reached, an
        // instantiation graded within a component's fixpoint, a stretch of
        // adjacency a walk scans or a condition reads to find its matches.
        // Counting the facts entered alone did not bound the time: in the
        // transitive closure of a ring, each fact arises from as many
        // instantiations as the ring contains members, and 19 601 facts took
        // 8 s.
        void charge(ExplainContext& ctx, const std::size_t units)
        {
            ctx.work += units;
            if (ctx.work >= ctx.work_limit) spent(ctx);
        }

        // The same, where the search is unable to halt midway -- within a
        // component's fixpoint. Once completed, the search examines the bound.
        void charge_quietly(ExplainContext& ctx, const std::size_t units)
        {
            ctx.work += units;
        }

        // The adjacency entries one unit stands for: those a walk scans, and
        // those a condition or a negation reads to find the facts it is
        // matched against (Unification::scanned). A walk is charged its edges
        // as well.
        constexpr std::size_t scan_per_unit = 64;

        // The candidate facts a single unit represents that a condition or
        // negation tries without a match (Unification::fruitless), or whose
        // matches it takes before the search asks for them (Join::suspend).
        // Each match the search takes constitutes an independent unit. Trying
        // a candidate incurs a cost several times greater than merely reading
        // it, yet only the reading was charged: a chain that attempted ten
        // thousand candidates per step without success -- each a statement
        // differing from the one the condition required -- reverted to the
        // search within the limit after 1.1 s, and one with a hundred
        // thousand per step after 2.5 s. Four such attempts per unit result
        // in a unit of such a search lasting 1 us to 2 us, and up to 4 us
        // when every step tries a hundred thousand.
        constexpr std::size_t tries_per_unit = 4;

        // Break down a rule's condition part into positive conditions, NAF
        // conditions, != guards, transitive path conditions (both plain
        // and negated), and detect neural conditions. Apply the same
        // detection mechanism used by Reasoning::evaluate: detect
        // conjunction sets through (IsA Conjunction) along with PartOf
        // membership, identify negation by the presence of the
        // (IsA Negation) tag on the pattern itself, and handle all other
        // cases based on the declared relation type of the condition.
        //
        // `parts`, when provided, gathers each node that the reading
        // examined.
        void collect_conditions(Zelph* z, const Node nn_pred, const Node closure_pred, const Node part, std::vector<Node>& positive, std::vector<Node>& negative, std::vector<Node>& guards, std::vector<Node>& closures, std::vector<Node>& negated_closures, bool& neural, std::vector<Node>* parts = nullptr)
        {
            if (parts != nullptr) parts->push_back(part);
            if (z->is_condition_set(part))
            {
                for (const Node rel : z->get_right(part))
                {
                    if (z->parse_relation(rel) != z->core.PartOf) continue;
                    adjacency_set objs;
                    const Node    element = z->parse_fact(rel, objs);
                    if (element && objs.count(part) == 1)
                        collect_conditions(z, nn_pred, closure_pred, element, positive, negative, guards, closures, negated_closures, neural, parts);
                }
                return;
            }

            const adjacency_set rels = z->filter(part, z->core.IsA, z->core.RelationTypeCategory);

            if (z->check_fact(part, z->core.IsA, {z->core.Negation}).is_known())
            {
                // A negated path condition is a walk too, not a pattern: when
                // tested as such, it never matched -- a walk lacks a fact node
                // -- thus it was reported as absent despite the path being
                // present.
                if (closure_pred != 0 && rels.size() == 1 && *rels.begin() == closure_pred)
                    negated_closures.push_back(part);
                else
                    negative.push_back(part);
                return;
            }

            if (rels.size() == 1)
            {
                if (*rels.begin() == z->core.Unequal)
                {
                    guards.push_back(part);
                    return;
                }
                if (nn_pred != 0 && *rels.begin() == nn_pred)
                {
                    neural = true;
                    return;
                }
                // A path condition holds by a WALK, so it has no fact node to
                // resolve to. Left among the positive conditions it made every
                // derivation through a path condition unreconstructible: the
                // join looked for the tag fact, found nothing, and .explain
                // answered "asserted; no derivation found" about a fact whose
                // deduction line had named its premises correctly.
                if (closure_pred != 0 && *rels.begin() == closure_pred)
                {
                    closures.push_back(part);
                    return;
                }
            }

            positive.push_back(part);
        }

        // A path condition under complete bindings: both ends have to be
        // ground, and then it is the same reachability test the forward pass
        // runs -- Zelph::transitive_targets, the indexed closure.
        //
        // `verifiable` reports whether the test could be made at all. An end
        // that no other condition bound would need the GENERATOR reading, and
        // generating from a proof is a different question from checking one;
        // the rule is then skipped exactly as a neural condition is, which
        // leaves the honest "no derivation found" rather than a guess.
        bool closure_holds(ExplainContext& ctx, const Node condition, const Variables& bindings, bool& verifiable);

        // How many adjacency entries a walk may scan before the indexed
        // closure answers instead: this is the budget set for
        // Zelph::transitive_targets' own direct walk, ensuring a test costs
        // no more than before. Determining the edges of a walk
        // (walk_premises) may scan more, as only the walk itself is aware of
        // them.
        constexpr std::size_t closure_scan = std::size_t{1} << 16;
        constexpr std::size_t walk_scan    = std::size_t{1} << 20;

        // The walk a path condition asks for under complete bindings: from
        // where, to where, over which predicate, and whether zero steps are
        // allowed. False when the condition is malformed or if an end is
        // not bound.
        struct Path
        {
            Node from{0};
            Node to{0};
            Node step{0};
            bool reflexive{false};
        };

        bool path_of(Zelph* z, const Node closure_zero_plus, const Node condition, const Variables& bindings, Path& path)
        {
            adjacency_set modes;
            const Node    pattern = z->parse_fact(condition, modes, 0);
            if (pattern == 0 || modes.size() != 1) return false;
            path.reflexive = (*modes.begin() == closure_zero_plus);

            adjacency_set objects;
            const Node    from_pattern = z->parse_fact(pattern, objects, condition);
            const Node    step         = z->parse_relation(pattern);
            if (from_pattern == 0 || step == 0 || objects.size() != 1) return false;

            const auto resolved = [&](const Node n) -> Node
            {
                if (!Zelph::is_var(n)) return n;
                const auto it = bindings.find(n);
                return it == bindings.end() ? n : it->second;
            };

            path.from = resolved(from_pattern);
            path.to   = resolved(*objects.begin());
            path.step = resolved(step);
            return !Zelph::is_var(path.from) && !Zelph::is_var(path.to) && !Zelph::is_var(path.step);
        }

        // A shortest walk the path asks for, around the facts listed in
        // `avoid` and those never asserted, as the facts it steps over.
        bool transitive_walk(ExplainContext& ctx, const Path& path, const adjacency_set* avoid, std::vector<Node>& edges, bool& exhausted)
        {
            std::size_t scanned = 0;
            const bool  found   = ctx.z->transitive_walk(path.from, path.to, path.step, path.reflexive, ctx.unasserted.get(), avoid, walk_scan, edges, exhausted, &scanned);
            charge(ctx, 1 + edges.size() + scanned / scan_per_unit);
            return found;
        }

        bool closure_holds(ExplainContext& ctx, const Node condition, const Variables& bindings, bool& verifiable)
        {
            Path path;
            verifiable = path_of(ctx.z, ctx.closure_zero_plus, condition, bindings, path);
            if (!verifiable) return false;

            // A walk that halts upon arriving at the end. The closure
            // originating at the start traversed every adjacency linked to a
            // hub, and a chain of path conditions leading to the hub `good`
            // incurred a cost equal to the square of its length.
            std::vector<Node> edges;
            bool              exhausted = false;
            std::size_t       scanned   = 0;
            const bool        found     = ctx.z->transitive_walk(path.from, path.to, path.step, path.reflexive, ctx.unasserted.get(), nullptr, closure_scan, edges, exhausted, &scanned);
            charge(ctx, 1 + scanned / scan_per_unit);
            if (found) return true;
            return exhausted && ctx.z->transitive_targets(path.from, path.step, path.reflexive).count(path.to) != 0;
        }

        // != guard under complete bindings: violated only when both sides
        // resolve to the SAME concrete node (mirrors the forward pass).
        bool guard_holds(Zelph* z, const Node guard, const Node rule, const Variables& vars)
        {
            adjacency_set objs;
            const Node    subj = z->parse_fact(guard, objs, rule);
            const Node    obj  = objs.empty() ? 0 : *objs.begin();
            if (subj == 0 || obj == 0) return true; // malformed guard: the forward pass skips it too

            Node lhs = subj;
            Node rhs = obj;
            if (Zelph::is_var(lhs))
                if (const auto it = vars.find(lhs); it != vars.end()) lhs = it->second;
            if (Zelph::is_var(rhs))
                if (const auto it = vars.find(rhs); it != vars.end()) rhs = it->second;

            if (!Zelph::is_var(lhs) && !Zelph::is_var(rhs)) return lhs != rhs;
            return true; // an unbound side cannot witness a violation
        }

        // Whether a node a condition resolved to holds as a premise, via the
        // test the forward pass applies to every candidate fact (Unification):
        // a ground rule pattern exists solely due to a rule being authored
        // with it, and a refuted fact is held as known NOT to hold, thus
        // neither qualifies as data. The lookup that resolves a condition
        // finds both all the same, and the search proved facts through a
        // rule's own ground condition -- printed as
        // "[rule pattern; not asserted]" -- and announced it as a second
        // justification.
        bool premise_holds(const Zelph* z, const Node premise)
        {
            return !z->is_rule_pattern(premise) && !z->is_refuted_fact(premise);
        }

        // The maximum number of objects that a fact involving `subject` and
        // `predicate` carries, identified once per explanation.
        std::size_t widest(ExplainContext& ctx, const Node subject, const Node predicate)
        {
            auto& known = ctx.widest[subject];
            if (const auto it = known.find(predicate); it != known.end()) return it->second;

            std::size_t most = 0;
            for (const Node candidate : ctx.z->get_right(subject))
            {
                if (!ctx.z->has_right_edge(candidate, predicate)) continue;
                const auto structures = get_fact_structures(ctx.z, candidate, 1);
                for (const auto& fs : *structures)
                    if (fs.subject == subject && fs.predicate == predicate) most = std::max(most, fs.objects.size());
            }
            known.emplace(predicate, most);
            return most;
        }

        // The node a condition denotes under the given bindings, via lookup.
        // Unification matches a condition against a fact that carries MORE
        // objects -- `(X p Y)` binds Y to every object in `a p b c` -- thus
        // allowing a premise to be that wider fact (as per resolve_pattern's
        // `containing`). Looking for one involves scanning each fact
        // associated with the subject, and a join asks for each premise it
        // tries that is absent: in a materialized subclass closure, these
        // scans accounted for the majority of the explanation's cost. Whether
        // the subject possesses any fact involving the predicate with more
        // objects is asked once per explanation, rather than repeatedly.
        Resolve resolve_premise(ExplainContext& ctx, const Node condition, const Variables& bindings, Node& premise)
        {
            Zelph* const      z = ctx.z;
            std::vector<Node> history;
            const Resolve     exact = resolve_pattern(z, condition, bindings, premise, history, /*containing*/ false);
            if (exact != Resolve::Missing || !z->var_in_closure(condition)) return exact;

            // The parts, resolved exactly. When one of them is absent
            // too, the general lookup decides.
            const FactStructure fs        = get_preferred_structure(z, condition, 1);
            Node                subject   = 0;
            Node                predicate = 0;
            adjacency_set       objects;
            bool                parts = fs.predicate != 0
                                     && resolve_pattern(z, fs.subject, bindings, subject, history, false) == Resolve::Ok
                                     && resolve_pattern(z, fs.predicate, bindings, predicate, history, false) == Resolve::Ok;
            for (const Node o : fs.objects)
            {
                Node object = 0;
                if (!parts || resolve_pattern(z, o, bindings, object, history, false) != Resolve::Ok)
                {
                    parts = false;
                    break;
                }
                objects.insert(object);
            }
            if (!parts) return resolve_pattern(z, condition, bindings, premise, history, /*containing*/ true);

            if (widest(ctx, subject, predicate) <= objects.size()) return Resolve::Missing;
            if (const Node wider = containing_fact(z, subject, predicate, objects); wider != 0)
            {
                premise = wider;
                return Resolve::Ok;
            }
            return Resolve::Missing;
        }

        // A fact that carries the objects of `narrow` and more, within the
        // same subject and predicate.
        bool is_wider(const Zelph* z, const Node wider, const Node narrow)
        {
            const auto narrow_structures = get_fact_structures(z, narrow, 1);
            const auto wider_structures  = get_fact_structures(z, wider, 1);
            for (const auto& n : *narrow_structures)
            {
                for (const auto& w : *wider_structures)
                {
                    if (w.subject != n.subject || w.predicate != n.predicate || w.objects.size() <= n.objects.size()) continue;
                    if (std::all_of(n.objects.begin(), n.objects.end(), [&](const Node o)
                                    { return w.objects.count(o) != 0; }))
                        return true;
                }
            }
            return false;
        }

        // Another premise a ground condition might represent: a fact
        // involving its subject and predicate that carries additional
        // objects, which Unification also matches. Asked only once the exact
        // premise yielded no result. When a rule within a cycle had
        // materialized the exact fact -- (a p b) from (b q a), which the
        // wider (a p b c) had derived -- the search saw only (b q a) <=
        // (a p b) <= (b q a), and the derivation employed in the forward
        // pass was never tried.
        Node wider_premise(ExplainContext& ctx, const Node premise)
        {
            const auto structures = get_fact_structures(ctx.z, premise, 1);
            for (const auto& fs : *structures)
            {
                if (fs.predicate == 0 || Zelph::is_var(fs.subject)) continue;
                if (widest(ctx, fs.subject, fs.predicate) <= fs.objects.size()) continue;
                if (const Node wider = containing_fact(ctx.z, fs.subject, fs.predicate, fs.objects); wider != 0 && premise_holds(ctx.z, wider))
                    return wider;
            }
            return 0;
        }

        // The premise of a condition Unification just matched, under the
        // joined bindings: the fact it denotes, or the fact Unification read
        // the match from, provided that this latter one carries additional
        // objects -- also where the fact it denotes is present (refer to
        // wider_premise). 0: none that holds.
        Node enumerated_premise(ExplainContext& ctx, const Node condition, const Variables& joined, const Node matched)
        {
            Zelph* const      z       = ctx.z;
            Node              premise = 0;
            std::vector<Node> history;
            if (resolve_pattern(z, condition, joined, premise, history, /*containing*/ false) == Resolve::Ok)
            {
                if (matched != 0 && matched != premise && premise_holds(z, matched) && is_wider(z, matched, premise)) return matched;
                return premise_holds(z, premise) ? premise : 0;
            }
            if (resolve_premise(ctx, condition, joined, premise) != Resolve::Ok || !premise_holds(z, premise)) return 0;
            return premise;
        }

        // How many facts Unification scans to enumerate a condition given the
        // bindings: the edges emanating from the node it begins with -- the
        // subject when the bindings ground it, otherwise the first object --
        // or, when neither is grounded, every fact associated with the
        // predicate. A condition where the predicate is a variable starts
        // from each relation type that exists, regardless of other bindings:
        // `(X R Y)` with X bound appeared as the most constrained starting
        // point in the meta-rule `(R m S, X R Y) => (Y S X)`, and with three
        // thousand relation types, each instantiation consumed a millisecond.
        std::size_t scan_estimate(const ExplainContext& ctx, const Reasoning::ExplainRules::Shape& shape, const Variables& bindings)
        {
            Zelph* const z = ctx.z;
            if (shape.relation != 0 && Zelph::is_var(shape.relation)) return std::numeric_limits<std::size_t>::max();
            const auto ground = [&](const Node n) -> Node
            {
                if (n == 0) return 0;
                if (Zelph::is_var(n))
                {
                    const auto it = bindings.find(n);
                    return it == bindings.end() || Zelph::is_var(it->second) ? 0 : it->second;
                }
                if (!z->var_in_closure(n)) return n;
                Node              out = 0;
                std::vector<Node> history;
                return resolve_pattern(z, n, bindings, out, history) == Resolve::Ok ? out : 0;
            };
            if (const Node s = ground(shape.subject); s != 0) return z->right_count(s);
            if (const Node o = ground(shape.object); o != 0) return z->right_count(o);
            if (shape.relation != 0 && !Zelph::is_var(shape.relation)) return z->left_count(shape.relation);
            return std::numeric_limits<std::size_t>::max();
        }

        // The solutions of a rule's join, one at a time: bindings for all
        // variables within its positive conditions such that each
        // instantiated condition corresponds to an actual fact in the graph,
        // and these facts, the premises. A condition that is entirely ground
        // given the current bindings is confirmed via hash lookup; otherwise,
        // one is enumerated through the same (anchored, sequential)
        // Unification mechanism employed during the forward pass, seeded with
        // the current bindings, ensuring that matches only extend them
        // consistently. A premise relying on the fact currently being
        // constructed is a solution just like any other: the resolution of
        // its component determines its value.
        //
        // A generator, not a callback: the search arrives at the premises
        // of a solution before requesting the next one, and that involves
        // searches of its own (see Frame). Each level of the join keeps its
        // state here, on the heap.
        //
        // The condition enumerated is the first one, just as it has always
        // been, unless its starting point is a hub and another condition's
        // starting point is far narrower: within a chain, (X ok Z) with Z
        // bound starts from each `ok` fact, (X next n_i) from a single edge,
        // and joining the first one required a scan of the entire relation
        // for every fact searched -- the square of the chain's length. The
        // premises maintain the sequence provided by the join of the first
        // condition, which is the order a proof prints them in.
        class Join
        {
        public:
            Join(ExplainContext& ctx, const RuleInForce& r, Variables seed) : _ctx{ctx}, _r{r}
            {
                for (const auto& [variable, value] : seed)
                    if (!Zelph::is_var(value)) _seeded.push_back(variable);
                Level first;
                first.conditions.resize(r.positive.size());
                std::iota(first.conditions.begin(), first.conditions.end(), std::size_t{0});
                first.bindings = std::move(seed);
                _levels.push_back(std::move(first));
            }

            // Progresses to the subsequent solution; false upon the
            // absence of any further solution.
            bool next()
            {
                if (_solution)
                {
                    _solution = false;
                    leave();
                }
                while (!_levels.empty())
                {
                    Level& l = _levels.back();
                    if (!l.started && !start(l)) continue;
                    if (_solution) return true;

                    Node      premise = 0;
                    Variables joined;
                    if (l.enumerated)
                    {
                        premise = next_match(l, joined);
                    }
                    else
                    {
                        if (l.tried == l.ground.size() && !l.widened)
                        {
                            l.widened = true;
                            if (const Node wider = wider_premise(_ctx, l.ground.front()); wider != 0) l.ground.push_back(wider);
                        }
                        if (l.tried < l.ground.size())
                        {
                            charge(_ctx, 1);
                            premise = l.ground[l.tried++];
                            joined  = l.bindings;
                        }
                    }
                    if (premise == 0)
                    {
                        leave();
                        continue;
                    }

                    Level child;
                    child.conditions = l.conditions;
                    child.conditions.erase(child.conditions.begin() + static_cast<std::ptrdiff_t>(l.chosen));
                    child.bindings = std::move(joined);
                    _facts.push_back(premise);
                    _order.push_back(l.conditions[l.chosen]);
                    _levels.push_back(std::move(child));
                }
                return false;
            }

            const Variables& bindings() const { return _levels.back().bindings; }

            // The search proceeds to the premises of the current solution, and
            // searching one can take a proof of its own, while every level of
            // the join stays open; a proof maintains a join open at each of its
            // steps. At the same time, a level releases its enumeration, along
            // with the candidates yet to be considered, which it might fail to
            // match even when the node it reads them from has the role assigned
            // by the condition (Unification::skip_candidates_in_other_roles): a
            // statement different from the one requested, a different count of
            // objects, or two nodes where the condition repeats a variable.
            // Held at each step of a proof spanning a thousand steps, ten
            // thousand of them required between 220 MB and 270 MB, whereas the
            // search that tested every candidate before it took a match, and
            // retained the matches, held 25 MB to 30 MB.
            //
            // A level whose enumeration has no remaining elements releases it:
            // in a chain spanning seventy thousand steps, with two such levels
            // per step, keeping them held 455 MB, while the search that kept no
            // enumeration held 289 MB. A level with a small number of
            // candidates remaining takes their matches ahead. One with a larger
            // number sets its enumeration aside and resumes it after the fact
            // it gave its final match from, once the search requests the next
            // match: taking every match ahead would try every candidate where
            // the search wants one additional match, or none at all. Resuming
            // an enumeration reads its candidates again, so a level resumed
            // twice takes its matches ahead during the next search; resumed for
            // each match, it would read them once per match.
            void suspend()
            {
                for (Level& l : _levels)
                {
                    if (!l.unify) continue;
                    if (l.unify->exhausted())
                        l.unify.reset();
                    else if (l.reopened >= reopened_at_most || l.unify->few_left(ahead_at_most))
                        take_ahead(l);
                    else
                        set_aside(l);
                }
            }

            // The premises of the current solution, listed in the sequence
            // determined by the join operation that always enumerates the
            // first condition left.
            std::vector<Node> premises() const
            {
                if (!_reordered) return _facts;

                std::unordered_set<Node> bound(_seeded.begin(), _seeded.end());
                std::vector<std::size_t> left(_r.positive.size());
                std::iota(left.begin(), left.end(), std::size_t{0});
                std::vector<Node> ordered;
                while (!left.empty())
                {
                    std::size_t pick = 0;
                    for (std::size_t k = 0; k < left.size(); ++k)
                    {
                        const auto& variables = _r.shapes[left[k]].variables;
                        if (std::all_of(variables.begin(), variables.end(), [&](const Node v)
                                        { return bound.count(v) != 0; }))
                        {
                            pick = k;
                            break;
                        }
                    }
                    const std::size_t condition = left[pick];
                    for (std::size_t j = 0; j < _order.size(); ++j)
                        if (_order[j] == condition) ordered.push_back(_facts[j]);
                    bound.insert(_r.shapes[condition].variables.begin(), _r.shapes[condition].variables.end());
                    left.erase(left.begin() + static_cast<std::ptrdiff_t>(pick));
                }
                return ordered;
            }

        private:
            static constexpr std::size_t ahead_at_most    = 64; // see suspend
            static constexpr std::size_t reopened_at_most = 2;

            // A match taken before the search requested it, and the fact it
            // was read from (see suspend).
            struct Match
            {
                std::shared_ptr<Variables> bindings;
                Node                       fact{0};
            };

            struct Level
            {
                std::vector<std::size_t>     conditions; // indices into the rule's positive conditions, yet to join
                Variables                    bindings;
                std::size_t                  chosen{none};      // the position in `conditions` this level joins
                bool                         enumerated{false}; // the condition is enumerated, not verified by lookup
                std::unique_ptr<Unification> unify;             // enumerating it, while it is open
                std::size_t                  read{0};           // the units charged for what `unify` read and tried
                std::size_t                  drained{0};        // the matches `unify` gave ahead
                std::vector<Match>           ahead;             // matches provided before being requested, served first
                std::size_t                  next_ahead{0};
                Node                         aside_relation{0}; // where the enumeration set aside stood: the relation
                Node                         aside_fact{0};     // and the fact it gave its last match from
                std::size_t                  reopened{0};       // how often it was taken up again
                std::vector<Node>            ground;            // a ground condition's premise, then the wider fact
                std::size_t                  tried{0};
                bool                         widened{false};
                bool                         started{false};
            };

            // The subsequent match for a level's condition whose premise
            // holds, along with its associated bindings; 0 if no such
            // match exists. Unification takes the facts in the sequence
            // dictated by their ids (Unification::enumerate_by_id). When no
            // specific order is enforced, it proceeds according to the
            // sequence in which the facts were inserted into the starting
            // node, an order that varies across distinct parallel runs,
            // causing the instantiation the search recorded first -- namely,
            // the one a proof shows and the step the SCC rule performs -- to
            // differ between two runs on the same graph. Node ids are content
            // hashes, hence their order is the graph's own.
            //
            // Each match is retrieved individually, as the search demands.
            // All had been enumerated and sorted before the initial
            // attempt, and a join whose first solution produced a clean
            // proof incurred a cost equivalent to the number of
            // matches in its condition: a hundred thousand for a fact
            // across as many groups. What a level holds during the
            // search's processing of a match's premise, see suspend.
            Node next_match(Level& l, Variables& joined)
            {
                const Node condition = _r.positive[l.conditions[l.chosen]];
                for (;;)
                {
                    std::shared_ptr<Variables> match;
                    Node                       fact = 0;
                    if (l.next_ahead < l.ahead.size())
                    {
                        Match& m = l.ahead[l.next_ahead++];
                        match    = std::move(m.bindings);
                        fact     = m.fact;
                    }
                    else
                    {
                        if (!l.ahead.empty())
                        {
                            std::vector<Match>().swap(l.ahead);
                            l.next_ahead = 0;
                        }
                        if (l.aside_relation != 0) reopen(l);
                        if (!l.unify) return 0;
                        match = l.unify->Next();
                        charge_read(l);
                        if (!match)
                        {
                            l.unify.reset();
                            return 0;
                        }
                        fact = l.unify->matched_fact();
                    }
                    joined = l.bindings;
                    for (const auto& [k, v] : *match)
                        joined[k] = v;
                    charge(_ctx, 1);
                    if (const Node premise = enumerated_premise(_ctx, condition, joined, fact); premise != 0) return premise;
                }
            }

            // The adjacency the level's Unification has read since it was
            // last charged, and the candidates it has attempted without
            // success or given ahead (see scan_per_unit, tries_per_unit).
            void charge_read(Level& l)
            {
                const std::size_t units = l.unify->scanned() / scan_per_unit + (l.unify->fruitless() + l.drained) / tries_per_unit;
                if (units == l.read) return;
                const std::size_t more = units - l.read;
                l.read                 = units;
                charge(_ctx, more);
            }

            // Opens the enumeration of the level's condition.
            void open(Level& l)
            {
                Zelph* const z = _ctx.z;
                charge(_ctx, 1 + (Zelph::is_var(_r.shapes[l.conditions[l.chosen]].relation) ? z->right_count(z->core.RelationTypeCategory) / scan_per_unit : 0));
                const auto variables = std::make_shared<Variables>(l.bindings);
                const auto unequals  = std::make_shared<Variables>();
                l.unify              = std::make_unique<Unification>(z, _r.patterns[l.conditions[l.chosen]], _r.rule, variables, unequals, /*pool*/ nullptr, /*log_depth*/ 1, /*profiler*/ nullptr);
                l.unify->enumerate_by_id();
                l.unify->skip_candidates_in_other_roles();
                l.enumerated = true;
                l.read       = 0;
                l.drained    = 0;
            }

            // Takes up an enumeration that was previously set aside where it
            // stood (see suspend). The candidates are read once more, and
            // charged once again.
            void reopen(Level& l)
            {
                open(l);
                l.unify->start_after(l.aside_relation, l.aside_fact);
                l.aside_relation = 0;
                l.aside_fact     = 0;
                ++l.reopened;
            }

            // Gives the rest of a level's matches ahead and releases its
            // enumeration.
            void take_ahead(Level& l)
            {
                while (std::shared_ptr<Variables> match = l.unify->Next())
                {
                    l.ahead.push_back({std::move(match), l.unify->matched_fact()});
                    ++l.drained;
                    charge_read(l);
                }
                charge_read(l);
                l.unify.reset();
            }

            // Lets go of a level's enumeration and keeps where it stood:
            // the fact it gave its last match from, whose additional matches
            // are given ahead.
            void set_aside(Level& l)
            {
                while (l.unify->has_queued())
                {
                    std::shared_ptr<Variables> match = l.unify->Next();
                    l.ahead.push_back({std::move(match), l.unify->matched_fact()});
                }
                l.aside_relation = l.unify->current_relation();
                l.aside_fact     = l.unify->matched_fact();
                l.unify.reset();
            }

            // A level's first step: a solution if nothing is left to join,
            // otherwise the condition it joins. False: the level represents a
            // dead end and has been left.
            bool start(Level& l)
            {
                Zelph* const z = _ctx.z;
                l.started      = true;
                if (l.conditions.empty())
                {
                    _solution = true;
                    return true;
                }

                // 1. Favour a fully ground condition: O(1) verification, and it
                //    binds nothing.
                for (std::size_t k = 0; k < l.conditions.size(); ++k)
                {
                    Node          premise = 0;
                    const Resolve r       = resolve_premise(_ctx, _r.positive[l.conditions[k]], l.bindings, premise);
                    if (r == Resolve::Unbound) continue;
                    // An exact node that does not hold -- a rule's own pattern,
                    // a refuted fact -- leaves the wider fact, which the forward
                    // pass also matches.
                    if (r == Resolve::Ok && !premise_holds(z, premise))
                    {
                        premise   = wider_premise(_ctx, premise);
                        l.widened = true;
                    }
                    if (r == Resolve::Missing || premise == 0)
                    {
                        leave(); // cannot hold under these bindings
                        return false;
                    }
                    l.chosen = k;
                    l.ground.push_back(premise);
                    return true;
                }

                // 2. Enumerate a condition that is not ground. A condition
                //    where the predicate is a variable starts from each
                //    relation type.
                l.chosen = anchored(l);
                open(l);
                return true;
            }

            // The position of the condition to enumerate: the initial one,
            // unless its start is a hub and another's is far narrower.
            std::size_t anchored(const Level& l)
            {
                constexpr std::size_t hub = 64;
                if (l.conditions.size() < 2) return 0;
                const std::size_t first = scan_estimate(_ctx, _r.shapes[l.conditions[0]], l.bindings);
                if (first <= hub) return 0;
                std::size_t best = 0, best_scan = first;
                for (std::size_t k = 1; k < l.conditions.size(); ++k)
                {
                    const std::size_t scan = scan_estimate(_ctx, _r.shapes[l.conditions[k]], l.bindings);
                    if (scan < best_scan)
                    {
                        best      = k;
                        best_scan = scan;
                    }
                }
                if (best == 0 || first / 4 <= best_scan) return 0;
                _reordered = true;
                return best;
            }

            void leave()
            {
                _levels.pop_back();
                if (_levels.empty()) return;
                _facts.pop_back();
                _order.pop_back();
            }

            ExplainContext&          _ctx;
            const RuleInForce&       _r;
            std::vector<Level>       _levels;
            std::vector<Node>        _facts; // the premise each level below the first was entered with
            std::vector<std::size_t> _order; // and the condition it instantiates
            std::vector<Node>        _seeded;
            bool                     _solution{false};
            bool                     _reordered{false};
        };

        // The stand-ins Unification matches the consequence with, should
        // it have any (Head::containers).
        const StandIns* stand_ins(const Reasoning::ExplainRules::Head& head)
        {
            return head.containers.empty() ? nullptr : &head.containers;
        }

        // Whether the consequence matched the fact directly, rather than
        // just a fact that encompasses additional objects: Unification
        // matches `(X p Y)` against `a p b c`, yet a specific instantiation
        // of the rule derives `a p b`, hence `a p b c` is not a consequence
        // of it. This remains valid even when `a p b` does not exist
        // (as of now): the instance refers to a node distinct from the fact,
        // which does exist. Only a consequence that matches while retaining
        // its own variables is accepted as is.
        //
        // A consequence over a collection that the firing replaces with a
        // term cannot be resolved here: the pattern names the rule's own
        // collection, and one that the firing gives a term of its own
        // represents any term. Its objects are counted instead, which tells
        // such a fact apart at the top level;
        // Reasoning::existing_consequence decides the remainder following
        // the join.
        bool concludes_exactly(Zelph* z, const Reasoning::ExplainRules::Head& head, const Variables& match, const Node fact)
        {
            if (!head.containers.empty())
            {
                adjacency_set objects;
                return z->parse_fact(fact, objects) != 0 && objects.size() == head.pattern.objects.size();
            }

            Node              hit = 0;
            std::vector<Node> history;
            switch (resolve_pattern(z, head.consequence, match, hit, history))
            {
            case Resolve::Ok:
                return hit == fact;
            case Resolve::Missing:
                return false;
            case Resolve::Unbound:
                break;
            }
            return true;
        }

        // Whether the consequence of some rule matches the given
        // fact: the starting stage of the search, excluding the joins.
        // Whether a consequence could ever match a fact belonging to the
        // specified predicate: in seed mode, Unification of a consequence
        // with a plain predicate yields no match with any other. Set up per
        // rule and fact all the same, across the hundreds of rules
        // in the maths stack, this process accounted for the bulk of the
        // expense in a deep explanation.
        bool may_match(const Reasoning::ExplainRules::Head& head, const Node fact_pred)
        {
            return head.predicate == 0 || head.predicate == fact_pred;
        }

        bool rule_matches(ExplainContext& ctx, const Node fact, const Node fact_pred)
        {
            Zelph* const z = ctx.z;
            for (const RuleInForce& r : ctx.rules)
            {
                for (const auto& head : r.heads)
                {
                    const Node cons = head.consequence;
                    if (cons == z->core.Contradiction || !may_match(head, fact_pred)) continue;
                    charge(ctx, 1);
                    const auto  vars = std::make_shared<Variables>();
                    const auto  uneq = std::make_shared<Variables>();
                    Unification u(z, head.pattern, r.rule, vars, uneq, nullptr, 1, /*profiler*/ nullptr, fact, fact_pred, Zelph::VariableReading::Text, stand_ins(head));
                    while (const std::shared_ptr<Variables> match = u.Next())
                        if (concludes_exactly(z, head, *match, fact)) return true;
                }
            }
            return false;
        }

        // Whether an instantiation constitutes a repetition of a proof's
        // justification: the identical rule applied to the same premises, as
        // demonstrated by `(A p X, A p Y, X != Y)` when X and Y are
        // interchanged.
        bool same_justification(const ProofNode& proof, const Node rule, const std::vector<Node>& premises)
        {
            if (proof.rule != rule) return false;
            std::unordered_set<Node> had;
            for (const auto& p : proof.premises)
                had.insert(p->fact);
            return had == std::unordered_set<Node>(premises.begin(), premises.end());
        }

        // The premises an instantiation shows, excluding the edges of its
        // walks.
        std::vector<Node> shown_facts(const Candidate& c)
        {
            const std::size_t n = std::min(c.shown, c.facts.size());
            return std::vector<Node>(c.facts.begin(), c.facts.begin() + static_cast<std::ptrdiff_t>(n));
        }

        // A fact that ends a proof without a derivation: a rule pattern, an
        // asserted fact some rule consequence matches (the search found no
        // instantiation that holds, or only those that rest on the fact's
        // own component), or an axiom.
        //
        // A rule that a statement mentions, named by the query, is not in
        // force (Zelph::is_mentioned), and no input. The node might also be a
        // typed rule, whose own node a statement names -- one that writes
        // identical text when that text hash-conses, one that a rule derives
        // from the typed rule's parts, or one that a script builds from the
        // rule node it holds -- and which then ceases firing, regardless of
        // whether its text holds a variable. The graph does not tell it from a
        // rule that is merely mentioned, so its label claims only what holds
        // either way. That label precedes the mark of a ground
        // pattern, which a ground rule that a switch mentions also carries.
        // A `=>` fact lacking the form of a rule is a fact just like any
        // other.
        //
        // As a premise, a mentioned rule is one that the engine has read as
        // input data -- a ground rule -- and is labelled as the input it was
        // read as.
        ProofNode::Status leaf_status(const ExplainContext& ctx, const Node fact, const bool unified)
        {
            if (fact == ctx.root && ctx.z->predicate_of(fact) == ctx.z->core.Causes && ctx.z->is_mentioned(fact) && ctx.z->has_rule_form(fact)) return ProofNode::Status::RuleMentioned;
            return ctx.z->is_rule_pattern(fact) ? ProofNode::Status::RulePattern
                 : unified                      ? ProofNode::Status::Unfounded
                                                : ProofNode::Status::Axiom;
        }

        Grade leaf_grade(const ProofNode::Status status)
        {
            return status == ProofNode::Status::Unfounded ? Grade::Founded : Grade::Clean;
        }

        std::shared_ptr<ProofNode> truncated_leaf(const Node fact)
        {
            auto proof    = std::make_shared<ProofNode>();
            proof->fact   = fact;
            proof->status = ProofNode::Status::Truncated;
            return proof;
        }

        void adopt(ProofNode& proof, const Candidate& c)
        {
            proof.status   = ProofNode::Status::Derived;
            proof.rule     = c.rule;
            proof.walked   = c.walked;
            proof.absent   = c.absent;
            proof.bindings = c.bindings;
            proof.premises.assign(c.premises.begin(), c.premises.begin() + static_cast<std::ptrdiff_t>(std::min(c.shown, c.premises.size())));
            proof.walk_edges.assign(c.walked.size(), {});
            for (std::size_t j = c.shown; j < c.premises.size() && j < c.walk_of.size(); ++j)
                if (c.walk_of[j] < proof.walk_edges.size()) proof.walk_edges[c.walk_of[j]].push_back(c.premises[j]);
        }

        bool depends_on_limit(const ExplainContext& ctx, const ProofNode* proof)
        {
            return proof->status == ProofNode::Status::Truncated || ctx.limited.count(proof) != 0;
        }

        // The facts that a proof holds an earlier result for, among those
        // `wanted` names: a leaf the depth limit cut, or a result that a
        // search from higher up has replaced since. Only proofs relying on
        // the depth limit can hold one, hence the walk remains confined
        // within them; it takes `start` itself into account.
        template <typename Wanted>
        void held(const ExplainContext& ctx, const ProofNode* start, const Wanted& wanted, std::vector<Node>& found)
        {
            if (!depends_on_limit(ctx, start)) return;
            std::vector<const ProofNode*>        todo{start};
            std::unordered_set<const ProofNode*> seen{start};
            while (!todo.empty())
            {
                const ProofNode* p = todo.back();
                todo.pop_back();
                if (wanted(p) && std::find(found.begin(), found.end(), p->fact) == found.end()) found.push_back(p->fact);
                for (const auto& premise : p->premises)
                    if (depends_on_limit(ctx, premise.get()) && seen.insert(premise.get()).second) todo.push_back(premise.get());
            }
        }

        // The facts being searched right now for which a complete proof holds
        // an earlier result. When reused as-is, the proof would show such a
        // fact beneath its own search: a derivation that appears to loop --
        // (:k o) nested within (:m o) nested within (:k o), with the innermost
        // segment truncated at the limit.
        std::vector<Node> held_open(const ExplainContext& ctx, const ProofNode* proof)
        {
            std::vector<Node> found;
            if (ctx.open_superseded == 0) return found;
            held(ctx, proof, [&](const ProofNode* p)
                 {
                     const auto it = ctx.table.find(p->fact);
                     return it != ctx.table.end() && !it->second.complete; },
                 found);
            return found;
        }

        // Whether a complete proof holds a fact above the one being searched
        // again within a finished tree (see restore_levels). Remembered per
        // proof, as the set remains unchanged throughout that search. The
        // proof is traversed using a stack specific to it, as deep as
        // it may be.
        bool holds_above(ExplainContext& ctx, const std::shared_ptr<ProofNode>& proof)
        {
            if (ctx.above.empty()) return false;

            const auto known = [&](const ProofNode* p) -> const bool*
            {
                const auto it = ctx.holds_above.find(p);
                return it == ctx.holds_above.end() ? nullptr : &it->second.second;
            };
            if (const bool* k = known(proof.get())) return *k;

            struct Step
            {
                std::shared_ptr<ProofNode> proof;
                std::size_t                next{0};
                bool                       found{false};
            };
            std::vector<Step> todo{{proof, 0, ctx.above.count(proof->fact) != 0}};
            while (!todo.empty())
            {
                Step& step = todo.back();
                if (!step.found && step.next < step.proof->premises.size())
                {
                    const std::shared_ptr<ProofNode> premise = step.proof->premises[step.next++];
                    if (const bool* k = known(premise.get()))
                        step.found = *k;
                    else
                        todo.push_back({premise, 0, ctx.above.count(premise->fact) != 0});
                    continue;
                }
                const bool                       found = step.found;
                const std::shared_ptr<ProofNode> done  = std::move(step.proof);
                todo.pop_back();
                ctx.holds_above.emplace(done.get(), std::make_pair(done, found));
                if (found && !todo.empty()) todo.back().found = true;
            }
            return *known(proof.get());
        }

        // A premise of an instantiation, as encountered during the search
        // process: its proof and grade, and whether it is part of a component
        // still being searched -- a member. A member's grade can only rise, so
        // one that is already clean is finalized, and an instantiation built
        // on it is not pending; the root is the exception, as whether an
        // instantiation that rests on the root constitutes a further
        // justification of it is decided once its component is complete.
        // `rests_on`: the facts being searched that the proof holds an earlier
        // result for. Absence of proof: the premise cannot be used here.
        struct Reached
        {
            std::shared_ptr<ProofNode> proof;
            Grade                      grade{Grade::Clean};
            bool                       member{false};
            bool                       settled{false};
            std::vector<Node>          rests_on;
        };

        Reached result(const Entry& e)
        {
            Reached r;
            r.proof = e.proof;
            r.grade = e.grade;
            return r;
        }

        Reached open_member(const ExplainContext& ctx, Entry& self, const Node fact, const Entry& member, const std::size_t link)
        {
            self.lowlink = std::min(self.lowlink, link);
            Reached r    = result(member);
            r.member     = true;
            r.settled    = member.grade == Grade::Clean && fact != ctx.root;
            return r;
        }

        bool concludes(ExplainContext& ctx, const Node fact)
        {
            if (const auto it = ctx.concludes.find(fact); it != ctx.concludes.end()) return it->second;
            const Node fact_pred = ctx.z->predicate_of(fact);
            const bool matched   = fact_pred != 0 && rule_matches(ctx, fact, fact_pred);
            ctx.concludes.emplace(fact, matched);
            return matched;
        }

        // A fact no rule consequence matches: complete in its
        // current form.
        Reached axiom(ExplainContext& ctx, const Node fact)
        {
            Entry& leaf        = ctx.table[fact];
            leaf.proof         = std::make_shared<ProofNode>();
            leaf.proof->fact   = fact;
            leaf.proof->status = leaf_status(ctx, fact, false);
            leaf.grade         = Grade::Clean;
            leaf.complete      = true;
            return result(leaf);
        }

        // A premise located at the depth limit, not tabled: a subsequent, less
        // deep instance might still be expandable. A fact that no rule
        // concludes is an axiom regardless of position, and is labelled as
        // one: it was once cut, just like any other when the search had not
        // encountered it previously, so a single tree could show it both as
        // "[axiom]" and as "[depth limit]".
        Reached at_limit(ExplainContext& ctx, const Node fact, const std::size_t depth)
        {
            if (!concludes(ctx, fact)) return axiom(ctx, fact);
            ctx.superseded.insert(fact);
            Reached r;
            r.proof = truncated_leaf(fact);
            ctx.limited.emplace(r.proof.get(), ExplainContext::Limited{r.proof, depth});
            return r;
        }

        // A premise within an instantiation of `self`, at `depth`: its
        // result immediately, or that the fact must be searched from `from`
        // first (see Frame), following which after_search makes the result.
        //
        // A complete result which is independent of the depth limit stands
        // anywhere. A result that is contingent on the limit was found with
        // the limit at a certain distance: from a deeper position, the limit
        // is closer, thus the result shows at least what that position
        // permits, yet from a strictly more shallow position the search gets
        // further, and the fact is searched again from that point -- at most
        // once per depth, hence at most max-depth times. Searching again from
        // a position that is not more shallow caused the count of searches to
        // increase with the depth limit, 15 293 searches of 528 facts at
        // limit 40.
        //
        // A result that holds an earlier result for a fact being searched
        // right now would show that fact beneath itself. This kind of result
        // is searched again from its own depth while the fact's own searches
        // leave room for it under the bound above, ensuring the fact is met
        // as what it is -- a member of the same component. Otherwise, the
        // instantiation rests on that fact: the component's fixpoint grades
        // it as though the fact were among its premises, thus it never
        // grounds the fact itself.
        struct Reach
        {
            Reached     reached;
            bool        search{false};
            std::size_t from{0};
        };

        Reach prepare(ExplainContext& ctx, Entry& self, const Node fact, const std::size_t depth)
        {
            charge(ctx, 1);
            Reach r;
            if (!ctx.above.empty() && ctx.above.count(fact) != 0) return r;

            std::size_t from = depth;
            if (const auto it = ctx.table.find(fact); it != ctx.table.end())
            {
                const Entry& known = it->second;
                if (!known.complete)
                {
                    r.reached = open_member(ctx, self, fact, known, known.index);
                    return r;
                }
                if (holds_above(ctx, known.proof)) return r;
                if (!known.truncated)
                {
                    r.reached = result(known);
                    return r;
                }
                if (depth >= known.depth)
                {
                    std::vector<Node> rests_on = held_open(ctx, known.proof.get());
                    if (rests_on.empty())
                    {
                        r.reached = result(known);
                        return r;
                    }
                    if (known.searches + known.depth >= ctx.max_depth)
                    {
                        for (const Node g : rests_on)
                            self.lowlink = std::min(self.lowlink, ctx.table.find(g)->second.index);
                        r.reached          = result(known);
                        r.reached.rests_on = std::move(rests_on);
                        return r;
                    }
                    from = known.depth;
                }
            }
            else if (ctx.max_depth != 0 && depth >= ctx.max_depth)
            {
                r.reached = at_limit(ctx, fact, depth);
                return r;
            }

            r.search = true;
            r.from   = from;
            return r;
        }

        // The result of the premise once its search has
        // ended.
        Reached after_search(const ExplainContext& ctx, Entry& self, const Node fact, const Entry& entered)
        {
            if (!entered.complete) return open_member(ctx, self, fact, entered, entered.lowlink);
            return result(entered);
        }

        // A premise's proof, when it is known to be clean without performing a
        // search: tabled as clean, beyond the depth limit, or a fact for which
        // no rule consequence matches. Otherwise, no proof.
        Reached known_clean(ExplainContext& ctx, Entry& self, const Node fact, const std::size_t depth)
        {
            if (!ctx.above.empty() && ctx.above.count(fact) != 0) return {};

            if (const auto it = ctx.table.find(fact); it != ctx.table.end())
            {
                const Entry& known = it->second;
                if (known.grade != Grade::Clean) return {};
                if (!known.complete) return fact == ctx.root ? Reached{} : open_member(ctx, self, fact, known, known.index);
                if (holds_above(ctx, known.proof)) return {};
                if (known.truncated && (depth < known.depth || !held_open(ctx, known.proof.get()).empty())) return {};
                return result(known);
            }

            if (ctx.max_depth != 0 && depth >= ctx.max_depth) return at_limit(ctx, fact, depth);
            if (concludes(ctx, fact)) return {};
            return axiom(ctx, fact);
        }

        // An instantiation the root found without open premises: a
        // justification of its own, as nothing within it rests on the
        // root.
        bool consider_at_root(ExplainContext& ctx, Entry& e, Candidate c)
        {
            if (e.grade != Grade::Clean && c.settled == Grade::Clean && !ctx.root_clean)
            {
                ctx.root_clean = true;
                ctx.work_limit = ctx.work + std::max(ctx.work, annotation_floor);
            }
            if (e.grade == Grade::Ungrounded)
            {
                adopt(*e.proof, c);
                e.grade = c.settled;
            }
            else if (c.settled > e.grade)
            {
                // The proof it supersedes continues to serve as a
                // justification of the root.
                ctx.more = true;
                adopt(*e.proof, c);
                e.grade = c.settled;
            }
            else if (!same_justification(*e.proof, c.rule, shown_facts(c)))
            {
                ctx.more = true;
            }
            e.candidates.push_back(std::move(c));

            // The root looks further for a clean proof and a second
            // justification: the annotation serves to indicate that a fact is
            // established via multiple routes, and a proof with all leaves
            // being axioms is favoured over one that rests on a leaf marked
            // "asserted; no derivation found".
            return e.grade == Grade::Clean && ctx.more;
        }

        // Under the root, a node maintaining a founded proof still takes a
        // clean one, but only if every premise is established as clean without
        // requiring a search. On Wikidata, nearly every asserted triple
        // matches a transitivity consequence, meaning almost every node
        // is founded instead of clean, and scanning every alternative of a
        // founded node made the search exponential. Returns true
        // upon taking the instantiation.
        bool founded_alternative(ExplainContext& ctx, Entry& e, const std::size_t depth, Candidate& c)
        {
            if (!c.rests_on.empty()) return false;
            for (const Node fact : c.facts)
            {
                const Reached reached = known_clean(ctx, e, fact, depth + 1);
                if (!reached.proof) return false;
                c.premises.push_back(reached.proof);
                c.member.push_back(reached.member);
            }
            adopt(*e.proof, c);
            e.grade = Grade::Clean;
            e.candidates.push_back(std::move(c));
            return true;
        }

        // A premise within an instantiation, reached: false if it is not
        // applicable in this context, thereby invalidating the
        // instantiation.
        bool take(Candidate& c, bool& open, Reached reached)
        {
            if (!reached.proof) return false;
            c.premises.push_back(reached.proof);
            c.member.push_back(reached.member);
            if (reached.member && !reached.settled)
                open = true;
            else
                c.settled = std::min(c.settled, reached.grade);
            for (const Node g : reached.rests_on)
                if (std::find(c.rests_on.begin(), c.rests_on.end(), g) == c.rests_on.end()) c.rests_on.push_back(g);
            return true;
        }

        // A single instantiation whose join, guards, path conditions, and
        // negations are satisfied, every premise reached. Returns true if the
        // fact does not require additional instantiation.
        bool conclude(ExplainContext& ctx, Entry& e, const std::size_t depth, Candidate c, const bool open)
        {
            // Pending: its value depends on how the component resolves. The
            // search proceeds to the next instantiation, which might not
            // need the component at all.
            if (open || !c.rests_on.empty())
            {
                e.candidates.push_back(std::move(c));
                return false;
            }

            if (depth == 0) return consider_at_root(ctx, e, std::move(c));

            // The first instantiation remains active as the fallback, and
            // only a better one supersedes it; a node stops at its first
            // clean instantiation.
            if (c.settled > e.grade)
            {
                adopt(*e.proof, c);
                e.grade = c.settled;
                e.candidates.push_back(std::move(c));
            }
            return e.grade == Grade::Clean;
        }

        // Whether the rest of an instantiation holds after the join has
        // assigned values to its variables: the != guards, the path
        // conditions, and the negations. On success `c` carries the paths
        // walked and the negated patterns found absent.
        bool rest_holds(ExplainContext& ctx, const RuleInForce& r, Candidate& c)
        {
            Zelph* const z = ctx.z;

            for (const Node g : r.guards)
                if (!guard_holds(z, g, r.rule, c.bindings)) return false;

            // Path conditions after the join, for the same reason the guards
            // are: the walk needs both ends ground, and it is the join that
            // grounds them.
            for (const Node p : r.closures)
            {
                bool verifiable = false;
                if (!closure_holds(ctx, p, c.bindings, verifiable) || !verifiable) return false;
                c.walked.push_back(p);
            }

            // NAF: a negated pattern that matches in the CURRENT graph
            // disqualifies this justification. It undergoes evaluation
            // identical to how the forward pass tests it -- the negation holds
            // only when NO fact matches under the given bindings -- because it
            // is NOT ground following the join: a variable appearing solely
            // within the negation, the S in ¬(T rw S), is quantified there and
            // remains unbound. Requesting the ground fact instead found the
            // pattern as unbound and interpreted that as absence, thus causing
            // a fact whose negated premise had become true to be displayed as
            // derived.
            //
            // The check reads the adjacency of the node it is anchored at, and
            // what it reads is charged (see scan_per_unit): a negation
            // anchored at a hub read a hundred thousand entries per check, for
            // one unit. Among the facts read at a bound subject or object that
            // is an atom, only those where it plays that role are tried; a hub
            // that served as the object in a hundred thousand facts of the
            // negated predicate had each one tried and rejected, eight times
            // the time the units represented, and the same occurred for one
            // that was their subject. The candidates it tries without success
            // are charged (see tries_per_unit).
            for (std::size_t k = 0; k < r.negative.size(); ++k)
            {
                const Node  m         = r.negative[k];
                const auto  held_vars = std::make_shared<Variables>(c.bindings);
                const auto  held_uneq = std::make_shared<Variables>();
                Unification held(z, r.negative_patterns[k], r.rule, held_vars, held_uneq, nullptr, 1, /*profiler*/ nullptr);
                held.skip_candidates_in_other_roles();
                const bool matched = held.Next() != nullptr;
                charge(ctx, 1 + held.scanned() / scan_per_unit + held.fruitless() / tries_per_unit);
                if (matched) return false; // the negated pattern is matched NOW

                // Keep the rule's PATTERN, not the ground node: the pattern
                // carries the (IsA Negation) tag, so it renders as ¬(...) on
                // its own, and the caller supplies `bindings` to substitute
                // the variables the join fixed. A ground node would render
                // without the negation and force the caller to re-add it --
                // which is how the display grew a second ¬ around a pattern
                // that already had one.
                c.absent.push_back(m);
            }

            // A negated path condition holds when the walk fails to discover
            // any path, the reading of the forward pass, which likewise
            // rejects one where the ends are not both bound. It appears
            // within the absent premises, represented as ¬(...) with the ends
            // the join bound.
            for (const Node p : r.negated_closures)
            {
                bool       verifiable = false;
                const bool walks      = closure_holds(ctx, p, c.bindings, verifiable);
                if (!verifiable || walks) return false;
                c.absent.push_back(p);
            }
            return true;
        }

        // The edges traversed by a walk of a path condition, serving as
        // premises for the step. A walk appears as a single [closure] line,
        // and was not searched: it hid a step across the fact under
        // explanation -- (a sub b) derived from (x in b), which walked a sub⁺
        // b over (a sub b) itself -- and across an edge that only that fact
        // derives, one step beyond. The edges of a single walk count like the
        // premises of the step, without being printed unless one ends the
        // proof (see Reasoning::ProofNode): an edge a rule concludes is
        // searched, an edge being searched makes the step wait for it, and the
        // component's fixpoint grades the step based on them. An edge no rule
        // concludes is an axiom, and adds nothing.
        //
        // The walk taken is a shortest one around the facts being searched.
        // Where every walk requires one of these, a single walk is taken
        // through them, and further instantiations take, for each such fact
        // along it, the walk that excludes it (`alternatives`): between two
        // routes, either may carry the step, and resting on all their edges
        // simultaneously caused it to wait for both. Only four were taken, and
        // the walk that omitted the one fact responsible for making the step
        // circular was the fifth. An edge that is discovered to be searched
        // only once the step arrives at it, and makes the step wait, is walked
        // around later (see rewalk). A predicate not concluded by any rule
        // possesses neither derived edges nor edges currently being searched,
        // thus its walks remain unchanged from their initial inspection -- the
        // class hierarchy of Wikidata, whose closure is too large to walk edge
        // by edge.
        //
        // Several path conditions, each encompassing multiple walks,
        // coalesce into no more than `walk_routes` instantiations.
        constexpr std::size_t walk_routes = 64;

        // The hidden premises of `c`, once again, extracted from its
        // shown ones and the edges of its walks, each precisely once,
        // following the order of the walks. Whether an edge is already
        // included among them is determined by consulting a set: when checked
        // against the list, it incurred a cost equal to the square of a
        // walk's length -- 3.4 s for a walk traversing 160 000 derived edges,
        // within a depth limit of one.
        void place_walks(ExplainContext& ctx, Candidate& c)
        {
            Zelph* const z = ctx.z;
            c.facts.resize(c.shown);
            c.walk_of.assign(c.shown, none);
            adjacency_set placed;
            for (const Node f : c.facts)
                placed.insert(f);
            for (const Walk& w : c.walks)
            {
                for (const Node e : w.edges)
                {
                    if (placed.count(e) != 0) continue;
                    const auto open_it = ctx.open_by_predicate.find(z->predicate_of(e));
                    const bool open    = open_it != ctx.open_by_predicate.end() && open_it->second.count(e) != 0;
                    if (!open && !concludes(ctx, e)) continue;
                    placed.insert(e);
                    c.facts.push_back(e);
                    c.walk_of.push_back(w.condition);
                }
            }
        }

        void walk_premises(ExplainContext& ctx, Candidate& c, std::vector<Candidate>& alternatives)
        {
            c.shown = c.facts.size();
            c.walk_of.assign(c.shown, none);
            if (c.walked.empty()) return;
            Zelph* const z = ctx.z;

            std::vector<std::vector<Walk>> routes{{}};
            for (std::size_t k = 0; k < c.walked.size(); ++k)
            {
                Path path;
                if (!path_of(z, ctx.closure_zero_plus, c.walked[k], c.bindings, path)) continue;
                if (!ctx.in_force->concludes_any && ctx.in_force->concluded.count(path.step) == 0) continue;

                const auto           open_it = ctx.open_by_predicate.find(path.step);
                const adjacency_set* open    = open_it == ctx.open_by_predicate.end() || open_it->second.empty() ? nullptr : &open_it->second;

                std::vector<Walk> walks;
                Walk              walk;
                walk.condition = k;
                bool exhausted = false;
                if (transitive_walk(ctx, path, open, walk.edges, exhausted))
                {
                    walks.push_back(std::move(walk));
                }
                else if (!exhausted && open != nullptr && transitive_walk(ctx, path, nullptr, walk.edges, exhausted))
                {
                    const std::vector<Node> through = walk.edges;
                    walks.push_back(std::move(walk));
                    for (const Node e : through)
                    {
                        if (open->count(e) == 0) continue;
                        Walk                around;
                        const adjacency_set left_out{e};
                        around.condition = k;
                        around.around    = {e};
                        if (!transitive_walk(ctx, path, &left_out, around.edges, exhausted)) continue;
                        if (std::none_of(walks.begin(), walks.end(), [&](const Walk& w)
                                         { return w.edges == around.edges; }))
                            walks.push_back(std::move(around));
                    }
                }
                if (walks.empty()) continue; // beyond the scan budget: the walk stands as it was checked

                std::vector<std::vector<Walk>> combined;
                for (const auto& route : routes)
                    for (const auto& w : walks)
                    {
                        if (combined.size() == walk_routes) break;
                        std::vector<Walk> both = route;
                        both.push_back(w);
                        combined.push_back(std::move(both));
                    }
                routes = std::move(combined);
            }

            for (std::size_t k = 1; k < routes.size(); ++k)
            {
                Candidate other = c;
                other.walks     = std::move(routes[k]);
                place_walks(ctx, other);
                alternatives.push_back(std::move(other));
            }
            c.walks = std::move(routes.front());
            place_walks(ctx, c);
        }

        // An instantiation in which the walk traversed edges that were found
        // to be searched upon the step's arrival -- an edge that rests on the
        // step's own conclusion, not yet searched when the walk occurred --
        // is followed by another whose walk circumvents those edges, provided
        // such a walk exists: the walk over (c sub b), which only the root
        // derives, yields to a -> d -> e -> b via edges of its own. Only an
        // edge that makes the step wait is relevant, one that remains
        // unsettled (see Reached).
        //
        // The further walk goes around each fact of the predicate being
        // searched, and when no such walk exists, around the edges that this
        // walk and the earlier ones met exclusively. It went around only the
        // facts being searched, including the settled ones: the walk around
        // (n3 sub b), which only the root derives, runs over (s sub u1),
        // which is being searched and clean, thus none was found, and the
        // root's step was printed over (n3 sub b) as "[asserted; no
        // derivation found]", even though the root holds without it. Omitting
        // the facts that are not settled would not work either: if (s sub u1)
        // holds via a fact that a rule concludes and none of its
        // instantiations leads to derivation, its proof is founded, it is not
        // settled while it is searched, and the walk over it constitutes the
        // sole existing one. A settled edge encountered by the walk is not
        // excluded: the only walk around the edge that makes the step wait
        // might pass over it. Each subsequent walk excludes one more edge
        // than the prior one, so this process terminates; after `rewalks` it
        // terminates regardless.
        //
        // The facts currently under search hold everything that an earlier
        // walk of the instantiation went around, along with every edge it
        // encountered: this runs while the frame of the instantiation's fact
        // lives, and a fact under search completes only with its component,
        // whose head is either that fact or one positioned beneath it. An
        // edge traversed by the walk was not included among the facts it
        // went around. Each walk kept a copy of these for the duration of
        // its instantiation's existence -- at each step of a chain, every
        // fact located above it: 1.2 GB across ten thousand steps. A walk
        // keeps the edges met (Walk::around), which the preceding walks had
        // crossed over.
        constexpr std::size_t rewalks = 32;

        std::optional<Candidate> rewalk(ExplainContext& ctx, const Candidate& c)
        {
            // A fact being searched that is already clean is settled (see
            // Reached), with the exception of the root: traversing it does
            // not make the step wait.
            const auto settled = [&](const Node fact)
            {
                if (fact == ctx.root) return false;
                const auto it = ctx.table.find(fact);
                return it != ctx.table.end() && it->second.grade == Grade::Clean;
            };

            for (std::size_t i = 0; i < c.walks.size(); ++i)
            {
                const Walk& w = c.walks[i];
                if (w.generation >= rewalks) continue;

                std::vector<Node> met;
                for (const Node f : w.around)
                    if (!settled(f)) met.push_back(f);
                const std::size_t before = met.size();
                for (std::size_t j = c.shown; j < c.facts.size(); ++j)
                    if (c.walk_of[j] == w.condition && c.member[j] && !settled(c.facts[j])) met.push_back(c.facts[j]);
                if (met.size() == before) continue;

                Path path;
                if (!path_of(ctx.z, ctx.closure_zero_plus, c.walked[w.condition], c.bindings, path)) continue;
                const auto open = ctx.open_by_predicate.find(path.step);
                if (open == ctx.open_by_predicate.end()) continue;

                Walk around;
                around.condition  = w.condition;
                around.generation = w.generation + 1;
                bool exhausted    = false;
                if (!transitive_walk(ctx, path, &open->second, around.edges, exhausted))
                {
                    if (exhausted) continue;
                    adjacency_set left_out;
                    for (const Node f : met)
                        left_out.insert(f);
                    if (left_out.size() >= open->second.size() || !transitive_walk(ctx, path, &left_out, around.edges, exhausted)) continue;
                }
                around.around = std::move(met);

                Candidate next;
                next.rule     = c.rule;
                next.bindings = c.bindings;
                next.walked   = c.walked;
                next.absent   = c.absent;
                next.facts.assign(c.facts.begin(), c.facts.begin() + static_cast<std::ptrdiff_t>(c.shown));
                next.shown    = c.shown;
                next.walks    = c.walks;
                next.walks[i] = std::move(around);
                place_walks(ctx, next);
                return next;
            }
            return std::nullopt;
        }

        // A single fact being searched: the extent to which the enumeration
        // of its instantiations has progressed -- each instantiation of
        // every rule in force whose consequence unifies with the fact,
        // processed in the sequence defined by ctx.rules -- along with the
        // instantiation whose premises are currently being reached. The
        // search keeps one such entry per fact it is inside of, stored on a
        // dedicated stack (see search).
        struct Frame
        {
            Node        fact{0};
            std::size_t depth{0};
            Entry*      e{nullptr};

            std::size_t                          rule{0}; // within ctx.rules
            std::size_t                          head{0}; // the following consequence of that rule
            Node                                 consequence{0};
            const Reasoning::ExplainRules::Head* matched{nullptr}; // the consequence's head
            bool                                 generator{false}; // the consequence is itself a rule
            Variables                            terms;            // the generator's variables left to its join (generator_seed)
            std::unique_ptr<Unification>         unify;            // the consequence's matches with the fact
            std::unique_ptr<Join>                join;             // the solutions for the present match

            std::vector<Candidate> queued; // instantiations that wait until it's their turn (see walk_premises)

            // The fact the consequence was matched with: either the fact
            // itself, or, for a membership of a term a firing built, a fact
            // that names the term (see next_membership_source). In this
            // context, `collection` refers to the collection of the rule's
            // text that the term represents, and a bucket seed lacks such a
            // fact: each firing of the rule builds the bucket's term using the
            // bucket's ground members.
            Node matched_fact{0};
            Node collection{0};
            bool bucket_seed{false};

            struct MembershipSource
            {
                std::size_t rule{0};
                std::size_t head{0};
                Node        naming{0};
                Node        collection{0};
            };
            std::optional<std::vector<MembershipSource>> sources; // read at the end of the heads

            Candidate   c;
            bool        considering{false};
            std::size_t premise{0};  // the following premise of `c` to reach
            bool        open{false}; // `c` has a premise in a component still being searched
            bool        done{false}; // the fact needs no additional instantiation
        };

        // Enters a fact: its table entry starts anew, positioned on
        // Tarjan's stack.
        void enter(ExplainContext& ctx, std::vector<Frame>& frames, const Node fact, const std::size_t depth)
        {
            Entry&            e        = ctx.table[fact];
            const std::size_t searches = e.searches;

            // The earlier result remains within the proofs that
            // hold it.
            if (e.proof) ctx.superseded.insert(fact);

            e             = Entry{};
            e.proof       = std::make_shared<ProofNode>();
            e.proof->fact = fact;
            e.index       = ctx.next_index++;
            e.lowlink     = e.index;
            e.depth       = depth;
            e.searches    = searches + 1;
            e.predicate   = ctx.z->predicate_of(fact);
            if (searches == 0) ++ctx.counts.facts;
            ++ctx.counts.searches;
            ctx.counts.most = std::max(ctx.counts.most, e.searches);
            if (ctx.superseded.count(fact) != 0) ++ctx.open_superseded;
            ctx.stack.push_back(fact);
            if (e.predicate != 0) ctx.open_by_predicate[e.predicate].insert(fact);

            Frame& f = frames.emplace_back();
            f.fact   = fact;
            f.depth  = depth;
            f.e      = &e;
        }

        // The bindings of a rule generator's own variables under which its
        // template builds the rule being explained, read off by comparing the
        // template and the rule side by side. The generator's join then
        // starts from these: starting from nothing, it built one rule per
        // solution and asked whether it was the one explained, and given the
        // thousands of rules a generator makes, explaining one of them took
        // seconds. No bindings -- a conjunction, several consequences,
        // relabelled variables -- leave the join as it was;
        // Reasoning::existing_rule determines the outcome regardless. No
        // value: the template is incapable of constructing this rule in any
        // way -- a constant differs, or a single pattern opposes a
        // conjunction -- and the generator does not need to be joined. Each
        // generator was, and a rule crafted by a second generator incurred a
        // join over the first one's thousands of solutions. `determined`: the
        // template and the rule determine every variable of the generator's
        // that the template holds, so the bindings are all the construction
        // reads.
        //
        // A variable that the rule holds a term for, and where the binding
        // itself is not present, is excluded from the seed and put into
        // `terms`: a construction writes a collection of rule text that the
        // generator bound as its data term (instantiate_fact), and the term's
        // identifier refers to no collection. Its binding is either
        // the term itself or a collection whose data term the term is, which
        // the join is tasked with locating, and stands_for_terms tells such a
        // solution from the others before the construction is asked. Either
        // binding builds this very rule, thus making the term count as
        // `determined`.
        std::optional<Variables> generator_seed(const ExplainContext& ctx, const RuleInForce& r, const Node consequence, const Node fact, bool& determined, Variables& terms)
        {
            determined = false;
            terms.clear();

            Zelph* const             z = ctx.z;
            std::unordered_set<Node> own;
            for (const auto& shape : r.shapes)
                own.insert(shape.variables.begin(), shape.variables.end());

            enum class Fit
            {
                Yes,
                Unknown,
                No
            };
            Variables                            seed;
            const std::function<Fit(Node, Node)> match = [&](const Node pattern, const Node node) -> Fit
            {
                if (pattern == node) return Fit::Yes;
                if (Zelph::is_var(pattern))
                {
                    if (own.count(pattern) == 0) return Fit::Unknown;
                    // A variable can meet its binding at the location where
                    // the construction kept it and the binding's data term
                    // where it wrote into it, since a condition set serves as
                    // both: the binding is the one whose data term the term
                    // is.
                    if (Zelph::is_value_recipe(node))
                    {
                        if (const auto bound = seed.find(pattern); bound != seed.end())
                            return Zelph::bucket_term_id(bound->second) == node ? Fit::Yes : Fit::No;
                        const auto [it, fresh] = terms.emplace(pattern, node);
                        return fresh || it->second == node ? Fit::Yes : Fit::No;
                    }
                    if (const auto term = terms.find(pattern); term != terms.end())
                    {
                        if (Zelph::bucket_term_id(node) != term->second) return Fit::No;
                        terms.erase(term);
                    }
                    const auto [it, fresh] = seed.emplace(pattern, node);
                    return fresh || it->second == node ? Fit::Yes : Fit::No;
                }
                if (z->is_condition_set(pattern)) return Fit::Unknown; // a conjunction: Reasoning::existing_rule decides

                // The construction reassembles a collection of the rule's
                // own text, and likewise reassembles every fact and set
                // constant located above it, regardless of whether they are
                // variable or not, so Reasoning::existing_rule decides; a
                // pattern that contains neither a variable nor such a
                // collection beneath it is the node that it builds.
                if (!Zelph::is_hash(pattern) && z->is_rule_template(pattern)) return Fit::Unknown;
                if (!z->var_in_closure(pattern) && !rule_text_below(z, pattern)) return Fit::No;
                if (!Zelph::is_hash(pattern) || !Zelph::is_hash(node) || z->is_condition_set(node))
                    return Zelph::is_hash(pattern) && z->is_condition_set(node) ? Fit::No : Fit::Unknown; // a pattern builds a single fact, not a conjunction
                const FactStructure p = get_preferred_structure(z, pattern, 1);
                const FactStructure n = get_preferred_structure(z, node, 1);
                if (p.predicate == 0 || n.predicate == 0 || p.objects.size() != 1 || n.objects.size() != 1) return Fit::Unknown;
                Fit fit = Fit::Yes;
                for (const auto& [a, b] : {std::pair{p.subject, n.subject}, std::pair{p.predicate, n.predicate}, std::pair{*p.objects.begin(), *n.objects.begin()}})
                {
                    const Fit part = match(a, b);
                    if (part == Fit::No) return Fit::No;
                    if (part == Fit::Unknown) fit = Fit::Unknown;
                }
                return fit;
            };
            switch (match(consequence, fact))
            {
            case Fit::No:
                return std::nullopt;
            case Fit::Unknown:
                terms.clear();
                return Variables{};
            case Fit::Yes:
                break;
            }
            determined = true;
            return seed;
        }

        // Whether the generator's join solution `bindings` binds each variable
        // in `terms` to its corresponding term or to a collection whose data
        // term it is (generator_seed). One hash for each such variable, where
        // asking the construction builds a rule.
        bool stands_for_terms(const Variables& terms, const Variables& bindings)
        {
            for (const auto& [variable, term] : terms)
            {
                const auto it = bindings.find(variable);
                if (it != bindings.end() && it->second != term && Zelph::bucket_term_id(it->second) != term) return false;
            }
            return true;
        }

        // The members within the
        // container `c`.
        std::vector<Node> members_of(const Zelph* const z, const Node c)
        {
            std::vector<Node> members;
            for (const Node rel : z->get_right(c))
            {
                if (z->predicate_of(rel) != z->core.PartOf) continue;
                adjacency_set objects;
                const Node    m = z->parse_fact(rel, objects, 0);
                if (m != 0 && objects.count(c) == 1) members.push_back(m);
            }
            return members;
        }

        // A membership `m in V` of a term a firing built is the content of
        // that term: the firing that derived the fact naming V built V with m
        // in it, and a bucket's term holds the bucket's ground members from
        // the first firing of its rule on. Those firings are its candidates,
        // once every consequence that matches the fact itself is tried: for
        // each fact naming V other than a membership of V, each consequence
        // over a collection the firing gives a term of its own; and for a
        // bucket whose term V is, the rule's every solution. Read once per
        // such fact, one pass over V's adjacency.
        std::vector<Frame::MembershipSource> membership_sources(const ExplainContext& ctx, const Frame& f)
        {
            Zelph* const                         z = ctx.z;
            std::vector<Frame::MembershipSource> sources;
            if (f.e->predicate != z->core.PartOf) return sources;

            adjacency_set objects;
            if (z->parse_fact(f.fact, objects) == 0 || objects.size() != 1) return sources;
            const Node term = *objects.begin();
            if (!Zelph::is_value_recipe(term)) return sources;

            for (std::size_t ri = 0; ri < ctx.rules.size(); ++ri)
            {
                if (ctx.rules[ri].neural) continue;
                for (std::size_t hi = 0; hi < ctx.rules[ri].heads.size(); ++hi)
                    for (const auto& [container, stand_in] : ctx.rules[ri].heads[hi].containers)
                        if (stand_in.term == term) sources.push_back({ri, hi, 0, container});
            }

            std::unordered_set<Node> naming;
            for (const adjacency_set& side : {z->get_left(term), z->get_right(term)})
                for (const Node fact : side)
                {
                    if (!Zelph::is_hash(fact) || fact == f.fact) continue;
                    adjacency_set held;
                    if (z->predicate_of(fact) == z->core.PartOf && z->parse_fact(fact, held, 0) != 0 && held.count(term) != 0) continue;
                    naming.insert(fact);
                }
            for (const Node fact : naming)
                for (std::size_t ri = 0; ri < ctx.rules.size(); ++ri)
                {
                    if (ctx.rules[ri].neural) continue;
                    for (std::size_t hi = 0; hi < ctx.rules[ri].heads.size(); ++hi)
                        for (const auto& [container, stand_in] : ctx.rules[ri].heads[hi].containers)
                            if (stand_in.term == 0) sources.push_back({ri, hi, fact, container});
                }
            return sources;
        }

        // Whether the firing under `bindings` builds the term of the fact's
        // membership containing the member: the instance of the collection is
        // that term and the member the instance of one of its members -- for
        // a bucket's term, of a ground member, under the empty key.
        bool builds_member(const ExplainContext& ctx, const Frame& f, const RuleInForce& r, const Variables& bindings)
        {
            Zelph* const  z = ctx.z;
            adjacency_set objects;
            const Node    member = z->parse_fact(f.fact, objects);
            if (member == 0 || objects.size() != 1) return false;
            const Node term = *objects.begin();

            if (f.bucket_seed)
            {
                // The bucket's statement binds none, keyed by no variable.
                const Variables none;
                const Recipe    own{f.collection, &none, RecipeMode::Firing, 0, nullptr};
                for (const Node m : members_of(z, f.collection))
                {
                    if (z->holds_variable_in_text(m)) continue;
                    std::vector<Node> history{f.collection};
                    if (ground_instance(z, m, none, 0, history, &own, Place{}, true) == member) return true;
                }
                return false;
            }

            const Recipe      recipe{f.consequence, &bindings, RecipeMode::Firing, r.condition, nullptr};
            std::vector<Node> history{f.consequence};
            if (ground_instance(z, f.collection, bindings, 0, history, &recipe, Place{}, true) != term) return false;
            for (const Node m : members_of(z, f.collection))
            {
                history = {f.consequence, f.collection};
                if (ground_instance(z, m, bindings, 0, history, &recipe, Place{}, true) == member) return true;
            }
            return false;
        }

        // Sets the frame to the next membership source, returning false
        // when no further source exists.
        bool next_membership_source(ExplainContext& ctx, Frame& f)
        {
            if (!f.sources) f.sources = membership_sources(ctx, f);
            if (f.sources->empty()) return false;

            const Frame::MembershipSource source = f.sources->front();
            f.sources->erase(f.sources->begin());

            const RuleInForce& r    = ctx.rules[source.rule];
            const auto&        head = r.heads[source.head];
            f.rule                  = source.rule;
            f.consequence           = head.consequence;
            f.matched               = &head;
            f.matched_fact          = source.naming;
            f.collection            = source.collection;
            f.bucket_seed           = source.naming == 0;

            charge(ctx, 1);
            if (f.bucket_seed)
            {
                f.join = std::make_unique<Join>(ctx, r, Variables{});
                return true;
            }
            const auto vars = std::make_shared<Variables>();
            const auto uneq = std::make_shared<Variables>();
            f.unify         = std::make_unique<Unification>(ctx.z, head.pattern, r.rule, vars, uneq, nullptr, 1, /*profiler*/ nullptr, source.naming, ctx.z->predicate_of(source.naming), Zelph::VariableReading::Text, stand_ins(head));
            return true;
        }

        // The next instantiation of the fact for which the join, guards,
        // path conditions, and negations hold, within `f.c`; returns false
        // when no such instantiation exists.
        bool next_candidate(ExplainContext& ctx, Frame& f)
        {
            Zelph* const z = ctx.z;
            if (f.e->predicate == 0) return false;
            if (!f.queued.empty())
            {
                f.c = std::move(f.queued.back());
                f.queued.pop_back();
                return true;
            }

            for (;;)
            {
                if (f.join)
                {
                    const RuleInForce& r = ctx.rules[f.rule];
                    while (f.join->next())
                    {
                        const Variables& bindings = f.join->bindings();

                        // A consequence that is itself a rule: the fact is a
                        // rule derived by a rule generator, established
                        // through an instantiation of the generator whose
                        // conditions hold, and under whose bindings the
                        // generator constructs precisely this rule.
                        // Unification does not match a rule-shaped template
                        // with a rule, thus the search enumerates the
                        // generator's join and asks the construction
                        // directly (Reasoning::existing_rule) to determine
                        // which rule each solution represents. As with any
                        // premise, the generator's conditions are facts; a
                        // fact derived THROUGH the generated rule reveals
                        // only its own premises, just as for a manually
                        // typed rule.
                        if (f.generator)
                        {
                            if (!stands_for_terms(f.terms, bindings)) continue;
                            charge(ctx, 1);
                            if (ctx.engine->existing_rule(f.consequence, bindings, 0, r.condition) != f.fact) continue;
                            f.e->unified = true;
                        }

                        // A consequence concerning a collection that the
                        // firing replaces by a term was matched with the
                        // term unresolved: the fact is this rule's solely
                        // when the firing under these bindings derives
                        // precisely it.
                        else if (!f.bucket_seed && !f.matched->containers.empty()
                                 && ctx.engine->existing_consequence(f.consequence, bindings, 0, r.condition) != f.matched_fact)
                            continue;

                        // A membership of a term: the firing builds it.
                        if (f.collection != 0)
                        {
                            charge(ctx, 1);
                            if (!builds_member(ctx, f, r, bindings)) continue;
                            f.e->unified = true;
                        }

                        Candidate c;
                        c.rule     = r.rule;
                        c.bindings = bindings;
                        c.facts    = f.join->premises();
                        if (!rest_holds(ctx, r, c)) continue;
                        walk_premises(ctx, c, f.queued);
                        std::reverse(f.queued.begin(), f.queued.end());
                        f.c = std::move(c);
                        return true;
                    }
                    f.join.reset();
                    if (f.generator)
                    {
                        f.generator = false;
                        continue;
                    }
                }

                if (f.unify)
                {
                    const RuleInForce& r = ctx.rules[f.rule];
                    while (const std::shared_ptr<Variables> match = f.unify->Next())
                    {
                        charge(ctx, 1);
                        // The match may bind the template to a fact that
                        // merely SUBSUMES the consequence (extra objects);
                        // permit solely instantiations representing precisely
                        // F. A match via a collection the firing replaces by
                        // a term constitutes a consequence matching the fact
                        // too, and the fact does not qualify as an axiom,
                        // even though the specific term the firing constructs
                        // is determined only after the join.
                        if (!concludes_exactly(z, *f.matched, *match, f.matched_fact)) continue;
                        if (f.collection == 0) f.e->unified = true;

                        // Neural premises cannot be verified structurally; do
                        // not reconstruct via this rule.
                        if (r.neural) break;

                        // Each join solution constitutes a candidate
                        // instantiation, not just the initial one: the first
                        // one's premises may rest on the fact itself --
                        // (ln of x) is marked for simplification by each
                        // term it appears within -- whereas an alternative
                        // solution to the same match leads to a proof.
                        f.join = std::make_unique<Join>(ctx, r, *match);
                        break;
                    }
                    if (f.join) continue;
                    f.unify.reset();
                    if (r.neural)
                    {
                        ++f.rule;
                        f.head = 0;
                    }
                }

                // The next consequence, and following the last one, for
                // a membership of a term, the firings that built the
                // term.
                for (;;)
                {
                    if (f.sources || f.rule >= ctx.rules.size())
                    {
                        if (!next_membership_source(ctx, f)) return false;
                        break;
                    }
                    const RuleInForce& r = ctx.rules[f.rule];
                    if (f.head >= r.heads.size())
                    {
                        ++f.rule;
                        f.head = 0;
                        continue;
                    }
                    const auto& head        = r.heads[f.head++];
                    const Node  consequence = head.consequence;
                    if (consequence == z->core.Contradiction) continue;
                    f.consequence = consequence;
                    f.matched     = &head;
                    if (head.produces_rule)
                    {
                        if (f.e->predicate != z->core.Causes || r.neural) continue;
                        bool                     determined = false;
                        std::optional<Variables> seed       = generator_seed(ctx, r, consequence, f.fact, determined, f.terms);
                        if (!seed) continue;

                        // The template and the rule, through their bindings,
                        // establish whether the consequence stands for the
                        // rule without the join: a rule authored by the
                        // generator is concluded by it also where no solution
                        // remains for its conditions, and is then a fact that
                        // has forfeited its justification, rather than an
                        // axiom.
                        if (determined && !f.e->unified)
                        {
                            charge(ctx, 1);
                            Variables read = *seed;
                            read.insert(f.terms.begin(), f.terms.end());
                            if (ctx.engine->existing_rule(consequence, read, 0, r.condition) == f.fact) f.e->unified = true;
                        }
                        f.generator = true;
                        f.join      = std::make_unique<Join>(ctx, r, std::move(*seed));
                        break;
                    }

                    // Seed-mode Unification: the candidate set is exactly
                    // {fact}, so Next() enumerates precisely the ways the
                    // consequence template unifies with the target.
                    if (!may_match(head, f.e->predicate)) continue;
                    const auto vars = std::make_shared<Variables>();
                    const auto uneq = std::make_shared<Variables>();
                    f.matched_fact  = f.fact;
                    f.unify         = std::make_unique<Unification>(z, head.pattern, r.rule, vars, uneq, nullptr, 1, /*profiler*/ nullptr, f.fact, f.e->predicate, Zelph::VariableReading::Text, stand_ins(head));
                    break;
                }
            }
        }

        // A premise the frame requires to be searched before
        // proceeding.
        struct Need
        {
            Node        fact{0};
            std::size_t depth{0};
        };

        // Extends the search of `f`'s fact to its fullest extent without
        // searching another fact: either toward a premise to search first,
        // or toward the end of its instantiations (yielding no fact in the
        // result).
        Need step(ExplainContext& ctx, Frame& f)
        {
            for (;;)
            {
                if (f.done) return {};
                if (f.considering)
                {
                    while (f.premise < f.c.facts.size())
                    {
                        const Node p = f.c.facts[f.premise];
                        Reach      r = prepare(ctx, *f.e, p, f.depth + 1);
                        if (r.search) return {p, r.from};
                        if (!take(f.c, f.open, std::move(r.reached)))
                        {
                            f.considering = false;
                            break;
                        }
                        ++f.premise;
                    }
                    if (f.considering)
                    {
                        f.considering = false;
                        if (std::optional<Candidate> around = rewalk(ctx, f.c)) f.queued.push_back(std::move(*around));
                        f.done = conclude(ctx, *f.e, f.depth, std::move(f.c), f.open);
                        if (f.depth == 0) ctx.alternative_from = ctx.next_index;
                    }
                    if (f.done) return {};
                    continue;
                }

                if (!next_candidate(ctx, f)) return {};
                if (f.depth != 0 && f.e->grade == Grade::Founded)
                {
                    if (founded_alternative(ctx, *f.e, f.depth, f.c))
                    {
                        f.done = true;
                        return {};
                    }
                    continue;
                }
                f.considering = true;
                f.premise     = 0;
                f.open        = false;
                if (f.depth == 0) ctx.alternative_from = ctx.next_index;
            }
        }

        // All members of a single strongly connected component are resolved
        // together, once the final one among them has been searched.
        struct Component
        {
            const ExplainContext&                 ctx;
            std::vector<Node>                     facts; // in entry order: the one the search entered through first
            std::vector<Entry*>                   members;
            std::unordered_map<Node, std::size_t> position;

            // For each member, the instantiations (member, candidate) that
            // include it as a member premise or rest on it.
            std::vector<std::vector<std::pair<std::size_t, std::size_t>>> dependents;

            Component(const ExplainContext& context, std::vector<Node> in_order, std::unordered_map<Node, Entry>& table) : ctx{context}, facts{std::move(in_order)}
            {
                for (std::size_t i = 0; i < facts.size(); ++i)
                {
                    members.push_back(&table.find(facts[i])->second);
                    position.emplace(facts[i], i);
                }
                dependents.resize(facts.size());
                for (std::size_t i = 0; i < members.size(); ++i)
                {
                    const std::vector<Candidate>& candidates = members[i]->candidates;
                    for (std::size_t k = 0; k < candidates.size(); ++k)
                    {
                        const Candidate& c = candidates[k];
                        for (std::size_t j = 0; j < c.facts.size(); ++j)
                            if (c.member[j])
                                if (const auto it = position.find(c.facts[j]); it != position.end())
                                    dependents[it->second].emplace_back(i, k);
                        for (const Node g : c.rests_on)
                            if (const auto it = position.find(g); it != position.end())
                                dependents[it->second].emplace_back(i, k);
                    }
                }
            }

            // Whether the instantiation requires the member `i` itself,
            // either as a premise or as a fact it rests on.
            bool needs_itself(const std::size_t i, const Candidate& c) const
            {
                const Node fact = facts[i];
                for (std::size_t j = 0; j < c.facts.size(); ++j)
                    if (c.member[j] && c.facts[j] == fact) return true;
                return std::find(c.rests_on.begin(), c.rests_on.end(), fact) != c.rests_on.end();
            }

            Grade grade_of(const Node fact, const std::vector<Grade>& grades) const
            {
                const auto it = position.find(fact);
                return it != position.end() ? grades[it->second] : ctx.table.find(fact)->second.grade;
            }

            // The number of instantiations the fixpoints graded: the
            // work of resolving the component (see charge_quietly).
            mutable std::size_t evaluations{0};

            Grade value(const Candidate& c, const std::vector<Grade>& grades) const
            {
                ++evaluations;
                Grade g = c.settled;
                for (std::size_t j = 0; j < c.facts.size(); ++j)
                    if (c.member[j]) g = std::min(g, grade_of(c.facts[j], grades));
                for (const Node f : c.rests_on)
                    g = std::min(g, grade_of(f, grades));
                return g;
            }

            // The least fixpoint: each member starts ungrounded, and its grade
            // increases to the highest value its instantiations produce based
            // on the grades of other members, continuing until no further
            // changes occur. Grades only increase, ensuring termination. A
            // member's proof is replaced only by a strictly better
            // instantiation, whose premises were already at that grade level
            // before the substitution, thereby preserving the absence of cycles
            // in every proof; the instantiations are tried in the sequence in
            // which the search built them, so the first one achieving a given
            // grade is the one shown. `fixed` members remain unchanged.
            void solve(std::vector<Grade>& grades, std::vector<std::size_t>& chosen, const std::vector<bool>& fixed) const
            {
                std::vector<std::size_t> changed;
                for (std::size_t i = 0; i < members.size(); ++i)
                {
                    if (fixed[i]) continue;
                    const std::vector<Candidate>& candidates = members[i]->candidates;
                    for (std::size_t k = 0; k < candidates.size(); ++k)
                    {
                        const Grade g = value(candidates[k], grades);
                        if (g <= grades[i]) continue;
                        grades[i] = g;
                        chosen[i] = k;
                    }
                    if (grades[i] != Grade::Ungrounded) changed.push_back(i);
                }
                raise(grades, chosen, fixed, std::move(changed));
            }

            void raise(std::vector<Grade>& grades, std::vector<std::size_t>& chosen, const std::vector<bool>& fixed, std::vector<std::size_t> changed) const
            {
                while (!changed.empty())
                {
                    const std::size_t j = changed.back();
                    changed.pop_back();
                    for (const auto& [i, k] : dependents[j])
                    {
                        if (fixed[i]) continue;
                        const Grade g = value(members[i]->candidates[k], grades);
                        if (g <= grades[i]) continue;
                        grades[i] = g;
                        chosen[i] = k;
                        changed.push_back(i);
                    }
                }
            }
        };

        // An instantiation created during the search of a single member might
        // hold, within a premise found complete, an earlier result for a
        // different member that the search entered only later -- a leaf cut
        // by the depth limit, or a result rediscovered from higher up.
        // Presented as it stands, this would place that member beneath
        // itself, hence it rests on the member, much like an instantiation
        // that meets such a result while the member is being searched
        // (see prepare).
        void rest_on_members(const ExplainContext& ctx, const std::vector<Node>& facts)
        {
            std::unordered_set<Node> superseded;
            for (const Node f : facts)
                if (ctx.superseded.count(f) != 0) superseded.insert(f);
            if (superseded.empty()) return;

            const auto wanted = [&](const ProofNode* p)
            { return superseded.count(p->fact) != 0; };
            for (const Node f : facts)
            {
                for (Candidate& c : const_cast<Entry&>(ctx.table.find(f)->second).candidates)
                {
                    for (std::size_t j = 0; j < c.premises.size(); ++j)
                        if (!c.member[j]) held(ctx, c.premises[j].get(), wanted, c.rests_on);
                }
            }
        }

        // THE SCC RULE. A member that remains ungrounded after the fixpoint
        // has been attained holds in the graph, yet every derivation the
        // search found for it runs back through its own component, and without
        // provenance there is no indication of which member was asserted. The
        // member via which the search ENTERED the component -- the first
        // ungrounded one in entry order -- keeps the first instantiation the
        // search recorded for it that relies on other members as premises, and
        // those members involved in that instantiation, provided they are
        // still ungrounded, turn into leaves, displayed as
        // "[asserted; no derivation found]"; a member lacking such an
        // instantiation itself becomes the leaf. The fixpoint resumes from the
        // leaves, and this process continues as long as ungrounded members
        // persist. In this vocabulary, "asserted" means "holds in the graph"
        // (as in "Fact is not asserted -- nothing to explain."), thus a leaf
        // precisely reflects what the engine knows: the fact holds, and every
        // derivation it identified runs back through the component. The rule
        // never prints a derivation that travels around a cycle; it stops one
        // step into such a cycle.
        //
        // That step is the point of the rule. zelph keeps no provenance, thus
        // it is unable to determine which member of a cycle was asserted, and
        // the rule instance that holds is more informative than none: the
        // derived mirror of a symmetric fact, a transitive or inherited fact
        // next to a cycle, used to be answered
        // "[asserted; no derivation found]" itself, when the facts it is
        // derived from were asserted and located just one step away. This is
        // also the output the search per path printed at the root. An asserted
        // edge within a cycle shows a single step toward each of the cycle's
        // members in turn, and they are labelled as what the engine is aware
        // of regarding them.
        //
        // `from`: the preceding members are grounded, and grades only
        // increase, thus each call proceeds from where the last one
        // stopped.
        std::vector<std::size_t> scc_leaves(const Component& component, const std::vector<Grade>& grades, std::size_t& from)
        {
            while (from < grades.size() && grades[from] != Grade::Ungrounded)
                ++from;
            if (from == grades.size()) return {};

            const std::size_t x = from;
            for (const Candidate& c : component.members[x]->candidates)
            {
                std::vector<std::size_t> used;
                bool                     through_itself = false;
                const auto               use            = [&](const Node fact)
                {
                    const auto it = component.position.find(fact);
                    if (it == component.position.end()) return;
                    if (it->second == x)
                        through_itself = true;
                    else if (grades[it->second] == Grade::Ungrounded && std::find(used.begin(), used.end(), it->second) == used.end())
                        used.push_back(it->second);
                };
                for (std::size_t j = 0; j < c.facts.size(); ++j)
                    if (c.member[j]) use(c.facts[j]);
                for (const Node g : c.rests_on)
                    use(g);
                if (!through_itself && !used.empty()) return used;
            }
            return {x};
        }

        // Whether the root possesses an additional justification: an
        // instantiation that differs from the one previously shown and
        // whose premises are grounded WITHOUT the root -- the fixpoint
        // once more, with the root maintained as ungrounded. Without
        // this, a rule that leads from the fact back to itself was
        // announced as a second route to it.
        //
        // A member that this fixpoint leaves ungrounded holds all the same,
        // and it is considered given when its support cannot pass through the
        // root: when no instantiation the search recorded for it connects to
        // the root via members left ungrounded -- a premise, or a fact it
        // rests on. A member grounded without the root does not carry a route
        // onward, and an instantiation requiring the member itself does not
        // serve as support for it: (:p0 a) <= (:p0 a), (:p2 a) indicated that
        // (:p0 a) holds solely through the root (:p2 a), and a true annotation
        // was lost.
        // That is what lets an asserted cycle that the search happened to
        // resolve together with the root count, just as it does when resolved
        // independently of it. A member that a fixpoint with only the root
        // grounded left ungrounded was also counted as given; however, such a
        // member might require the root in conjunction with another member --
        // (:f c) <= (:p c), (:x c), where (:x c) depends on the root -- and
        // every member within a cycle relies on another, so the annotation was
        // displayed alongside alternatives that rest on the root. The cost
        // remains unchanged: a premise that is asserted, yet also derived by
        // the root, does not count -- without provenance it cannot be told
        // from one derived exclusively from the root.
        bool further_justification(const Component& component, const std::size_t chosen)
        {
            const Entry&             root = *component.members[0];
            const std::size_t        n    = component.members.size();
            std::vector<std::size_t> unused(n, none);
            std::vector<bool>        fixed(n, false);
            fixed[0] = true;

            std::vector<Grade> without(n, Grade::Ungrounded);
            component.solve(without, unused, fixed);

            std::vector<bool>        reaches_root(n, false);
            std::vector<std::size_t> todo{0};
            reaches_root[0] = true;
            while (!todo.empty())
            {
                const std::size_t j = todo.back();
                todo.pop_back();
                for (const auto& [i, k] : component.dependents[j])
                {
                    if (reaches_root[i] || without[i] != Grade::Ungrounded) continue;
                    if (component.needs_itself(i, component.members[i]->candidates[k])) continue;
                    reaches_root[i] = true;
                    todo.push_back(i);
                }
            }

            std::vector<std::size_t> given;
            for (std::size_t i = 1; i < n; ++i)
            {
                if (without[i] != Grade::Ungrounded || reaches_root[i]) continue;
                without[i] = Grade::Founded;
                fixed[i]   = true;
                given.push_back(i);
            }
            component.raise(without, unused, fixed, std::move(given));

            for (std::size_t k = 0; k < root.candidates.size(); ++k)
            {
                if (k == chosen) continue;
                const Candidate& c = root.candidates[k];
                if (same_justification(*root.proof, c.rule, shown_facts(c))) continue;
                if (component.value(c, without) != Grade::Ungrounded) return true;
            }
            return false;
        }

        void complete_component(ExplainContext& ctx, const Node head)
        {
            std::vector<Node> facts;
            do
            {
                facts.push_back(ctx.stack.back());
                ctx.stack.pop_back();
            } while (facts.back() != head);
            std::reverse(facts.begin(), facts.end());

            rest_on_members(ctx, facts);
            const Component    component(ctx, std::move(facts), ctx.table);
            const std::size_t  n = component.members.size();
            std::vector<Grade> grades(n, Grade::Ungrounded);

            std::vector<std::size_t> chosen(n, none);
            std::vector<bool>        leaf(n, false);
            component.solve(grades, chosen, leaf);

            std::size_t from = 0;
            for (std::vector<std::size_t> leaves = scc_leaves(component, grades, from); !leaves.empty(); leaves = scc_leaves(component, grades, from))
            {
                for (const std::size_t x : leaves)
                {
                    leaf[x]   = true;
                    chosen[x] = none;
                    grades[x] = leaf_grade(leaf_status(ctx, component.facts[x], component.members[x]->unified));
                }
                component.raise(grades, chosen, leaf, std::move(leaves));
            }

            for (std::size_t i = 0; i < n; ++i)
            {
                Entry&     m     = *component.members[i];
                ProofNode& proof = *m.proof;
                m.truncated      = false;
                if (leaf[i])
                {
                    // A fact that lies on no cycle forms a standalone
                    // component, and if it lacks any derivation -- an
                    // axiom, or an asserted fact for which no instantiation
                    // holds -- the SCC rule designates it as its leaf.
                    // It is not a leaf within a cycle: a walk edge whose
                    // proof terminates at that point was displayed beneath
                    // its [closure] line (ProofNode::walk_edges).
                    proof.status     = leaf_status(ctx, component.facts[i], m.unified);
                    proof.cycle_leaf = n > 1 || std::any_of(m.candidates.begin(), m.candidates.end(), [&](const Candidate& c)
                                                            { return component.needs_itself(i, c); });
                    proof.rule       = 0;
                    proof.premises.clear();
                    proof.walked.clear();
                    proof.walk_edges.clear();
                    proof.absent.clear();
                    proof.bindings.clear();
                }
                else
                {
                    adopt(proof, m.candidates[chosen[i]]);
                }

                m.grade    = grades[i];
                m.complete = true;
                if (ctx.superseded.count(component.facts[i]) != 0) --ctx.open_superseded;
                if (m.predicate != 0) ctx.open_by_predicate[m.predicate].erase(component.facts[i]);
            }

            // A result depends on the depth limit if the proof it presents
            // includes a leaf that the limit cut, either directly or via a
            // premise -- another member's included. One whose shown proof the
            // limit did not cut remains valid anywhere, even if the search
            // encountered the limit among alternatives it bypassed: a less deep
            // search might have selected differently, yet the presented proof
            // is complete as it stands.
            for (bool changed = true; changed;)
            {
                changed = false;
                for (Entry* m : component.members)
                {
                    if (m->truncated) continue;
                    for (const auto& premise : m->proof->premises)
                    {
                        const auto it  = component.position.find(premise->fact);
                        const bool cut = depends_on_limit(ctx, premise.get())
                                      || (it != component.position.end() && component.members[it->second]->proof == premise && component.members[it->second]->truncated);
                        if (!cut) continue;
                        m->truncated = true;
                        changed      = true;
                        break;
                    }
                }
            }
            for (Entry* m : component.members)
                if (m->truncated) ctx.limited.emplace(m->proof.get(), ExplainContext::Limited{m->proof, m->depth});

            if (head == ctx.root && component.members[0]->proof->status == ProofNode::Status::Derived)
                component.members[0]->proof->more_justifications = further_justification(component, chosen[0]);
            charge_quietly(ctx, component.evaluations);

            for (Entry* m : component.members)
                std::vector<Candidate>().swap(m->candidates);
        }

        // The root holds a clean proof and has carried out the work it may
        // spend toward a further justification (see annotation_floor), either
        // midway through one or between two: the rest of that instantiation is
        // discarded, along with every fact that was entered for it and remains
        // open, and the root ceases further exploration -- step() stops at a
        // frame that is done. These facts form the top of Tarjan's stack,
        // starting from `alternative_from`: what the instantiation completed
        // is complete, and no prior complete item or fact entered earlier
        // holds an open fact positioned above it. Previously, the bound was
        // checked solely before the root began a premise, and a single premise
        // heading a chain of ten thousand facts was exhaustively searched to
        // its end; afterwards, the root proceeded to conclude its remaining
        // instantiations, hence the bound did not bound the enumeration.
        void abandon_alternative(ExplainContext& ctx, std::vector<Frame>& frames)
        {
            frames.resize(1);
            while (!ctx.stack.empty())
            {
                const Node   fact = ctx.stack.back();
                const auto   it   = ctx.table.find(fact);
                const Entry& e    = it->second;
                if (e.index < ctx.alternative_from) break;
                ctx.stack.pop_back();
                if (e.predicate != 0) ctx.open_by_predicate[e.predicate].erase(fact);
                if (ctx.superseded.count(fact) != 0) --ctx.open_superseded;
                ctx.table.erase(it);
            }
            Frame& root      = frames.front();
            root.considering = false;
            root.done        = true;
            root.queued.clear();
            ctx.work_limit = std::numeric_limits<std::size_t>::max();
        }

        // Searches a fact from `depth`, and with it every premise it reaches
        // that needs a search: establishes a frame for every fact on a
        // dedicated stack, with the innermost frame being processed until
        // either another fact must be searched or no instantiation remains.
        // Once a fact is completed, it closes its component if it heads one,
        // and its result is passed to the frame that reached it.
        Entry& search(ExplainContext& ctx, const Node fact, const std::size_t depth)
        {
            std::vector<Frame> frames;
            enter(ctx, frames, fact, depth);
            for (;;)
            {
                Need need;
                try
                {
                    need = step(ctx, frames.back());
                    if (need.fact != 0)
                    {
                        charge(ctx, 1);
                        if (frames.back().join) frames.back().join->suspend();
                    }
                }
                catch (const AnnotationSpent&)
                {
                    abandon_alternative(ctx, frames);
                    continue;
                }
                if (need.fact != 0)
                {
                    enter(ctx, frames, need.fact, need.depth);
                    continue;
                }

                Entry&     e        = *frames.back().e;
                const Node finished = frames.back().fact;
                if (e.lowlink == e.index) complete_component(ctx, finished);
                frames.pop_back();
                if (frames.empty())
                {
                    ctx.work_limit = std::numeric_limits<std::size_t>::max();
                    return e;
                }
                if (ctx.work >= ctx.work_limit && !ctx.root_clean) spent(ctx);

                Frame& f = frames.back();
                if (take(f.c, f.open, after_search(ctx, *f.e, finished, e)))
                    ++f.premise;
                else
                    f.considering = false;
            }
        }

        // The search reuses a result wherever its fact appears again, and the
        // component's fixpoint might show a proof at a location where the
        // search reached that fact from deeper down: within a cycle, a fact
        // initially encountered deep down gets reused higher up while the cycle
        // is still being searched, and its result, cut at the limit as seen
        // from deep within, stood there with "[depth limit]" far above the
        // actual limit. After the tree is completed, each result that depends
        // on the limit and exists higher than it was discovered -- starting
        // with the shallowest occurrence -- is searched again from there, as a
        // fact met higher up during the search is (see prepare): strictly
        // shallower, hence within the same bound. The new proof must not rest
        // on any fact situated above it in the tree, or else the tree would
        // place that fact beneath itself; any such premise is considered not to
        // hold there. The new result replaces the old one wherever the tree
        // holds it, unless it is inferior: if every derivation the search finds
        // from that point passes through facts positioned above, the old result
        // stays.
        void restore_levels(ExplainContext& ctx, const std::shared_ptr<ProofNode>& root)
        {
            if (ctx.max_depth == 0 || ctx.limited.empty()) return;

            std::unordered_set<const ProofNode*> kept;
            for (;;)
            {
                // The shallowest level of every node, and who holds it, in
                // breadth first order.
                std::unordered_map<ProofNode*, std::size_t>             level{{root.get(), 0}};
                std::unordered_map<ProofNode*, std::vector<ProofNode*>> holders;
                std::vector<ProofNode*>                                 order{root.get()};
                for (std::size_t i = 0; i < order.size(); ++i)
                {
                    ProofNode* const p = order[i];
                    for (const auto& premise : p->premises)
                    {
                        holders[premise.get()].push_back(p);
                        if (level.emplace(premise.get(), level[p] + 1).second) order.push_back(premise.get());
                    }
                }

                ProofNode* stale = nullptr;
                for (ProofNode* const p : order)
                {
                    const auto it = ctx.limited.find(p);
                    if (it == ctx.limited.end() || kept.count(p) != 0) continue;
                    if (level[p] < ctx.max_depth && it->second.depth > level[p])
                    {
                        stale = p;
                        break;
                    }
                }
                if (stale == nullptr) return;

                const Node   fact    = stale->fact;
                const auto   current = ctx.table.find(fact);
                const Entry* entry   = current != ctx.table.end() ? &current->second : nullptr;

                // Every element above the stale result, along each path
                // leading to it.
                ctx.above.clear();
                ctx.holds_above.clear();
                std::vector<ProofNode*>        todo{stale};
                std::unordered_set<ProofNode*> seen{stale};
                while (!todo.empty())
                {
                    ProofNode* const p = todo.back();
                    todo.pop_back();
                    for (ProofNode* const h : holders[p])
                    {
                        ctx.above.insert(h->fact);
                        if (seen.insert(h).second) todo.push_back(h);
                    }
                }

                // The current result of the fact might already be in place:
                // either one that does not depend on the limit, or one
                // found from a sufficiently elevated position.
                const bool fits = entry != nullptr && entry->complete && (!entry->truncated || entry->depth <= level[stale]);

                std::shared_ptr<ProofNode> replacement;
                if (fits && entry->proof.get() != stale && !holds_above(ctx, entry->proof))
                {
                    replacement = entry->proof;
                }
                else if (!fits)
                {
                    const Entry& again = search(ctx, fact, level[stale]);
                    replacement        = again.proof;
                }
                ctx.above.clear();
                ctx.holds_above.clear();

                const bool better = replacement != nullptr
                                 && (replacement->status == ProofNode::Status::Derived
                                     || (replacement->status == stale->status && stale->status != ProofNode::Status::Truncated));
                if (!better)
                {
                    kept.insert(stale);
                    continue;
                }
                for (ProofNode* const h : holders[stale])
                    for (auto& premise : h->premises)
                        if (premise.get() == stale) premise = replacement;
            }
        }
    } // namespace

    std::shared_ptr<ProofNode> Reasoning::explain(const Node fact, const std::size_t max_depth) const
    {
        // The unification machinery takes a mutable engine pointer, but this
        // reconstruction never creates nodes or edges: resolve_pattern and
        // check_fact are pure hash lookups, and Unification is constructed
        // without a thread pool, so it only reads the graph.
        Reasoning* const self = const_cast<Reasoning*>(this);

        const Node nn_pred           = get_node("nn", "zelph");
        const Node closure_pred      = get_node("closure", "zelph");
        const Node closure_zero_plus = get_node("zero-or-more", "zelph");

        // Rules are the facts where the predicate is core.Causes; the
        // subject corresponds to the condition segment, and the objects
        // represent the consequence templates. The identical rules as the
        // forward evaluators read, in the identical sequence: left adjacency
        // of the relation node, confirmed through parse_relation, excluding
        // the ones that are mentioned. Explaining does not write, thus the
        // list remains valid for the whole call -- and for the subsequent
        // one, provided it is read from the same nodes using the same edges.
        // Reading it meant a mention test for each rule, and with the
        // thousands of rules a generator produces, each explanation of an
        // axiom took seconds.
        const adjacency_set read_from = get_left(core.Causes);
        const auto          edges     = [&](const Node n)
        { return left_count(n) + right_count(n); };
        const std::uint64_t epoch      = graph_epoch();
        const bool          comparable = _explain_rules != nullptr && _explain_rules->nn_pred == nn_pred && _explain_rules->closure_pred == closure_pred && _explain_rules->epoch == epoch;
        const auto          same       = [&](const Node n, const std::size_t count)
        { return edges(n) == count && !touched_by_removal(n); };
        const auto unchanged = [&](const ExplainRules::Source& source)
        {
            if (!same(source.node, source.edges)) return false;
            for (const auto& [node, count] : source.watched)
                if (!same(node, count)) return false;
            return true;
        };
        bool current = comparable
                    && _explain_rules->read_from.size() == read_from.size();
        if (current)
        {
            std::size_t i = 0;
            for (const Node n : read_from)
            {
                const auto& source = _explain_rules->read_from[i++];
                if (source.node != n || !unchanged(source))
                {
                    current = false;
                    break;
                }
            }
        }
        if (!current)
        {
            // What remained unchanged is taken over: during a session,
            // introducing a rule between two explanations incurs cost
            // solely for that rule.
            std::unordered_map<Node, const ExplainRules::Source*> before;
            if (comparable)
                for (const auto& source : _explain_rules->read_from)
                    before.emplace(source.node, &source);

            auto fresh          = std::make_shared<ExplainRules>();
            fresh->nn_pred      = nn_pred;
            fresh->closure_pred = closure_pred;
            fresh->epoch        = epoch;
            for (const Node rule : read_from)
            {
                ExplainRules::Source& source = fresh->read_from.emplace_back();
                source.node                  = rule;
                source.edges                 = edges(rule);
                if (const auto it = before.find(rule); it != before.end() && unchanged(*it->second))
                {
                    source.watched = it->second->watched;
                    if (it->second->rule != none)
                    {
                        source.rule = fresh->rules.size();
                        fresh->rules.push_back(_explain_rules->rules[it->second->rule]);
                    }
                    continue;
                }
                if (parse_relation(rule) != core.Causes || is_mentioned(rule)) continue;

                RuleInForce r;
                r.rule      = rule;
                r.condition = self->parse_fact(rule, r.consequences);
                if (r.condition == 0 || r.consequences.empty()) continue;
                for (const Node cons : r.consequences)
                {
                    const Node predicate = parse_relation(cons);
                    auto&      head      = r.heads.emplace_back(ExplainRules::Head{cons, predicate == core.Causes, Node{0}, build_pattern_info(self, cons, 1), {}});

                    // Each collection that a firing substitutes with a term
                    // is watched with its edges, just as the parts of a
                    // condition are: a removal within its members may alter
                    // the kind of term it represents.
                    if (asserts_fact(cons))
                    {
                        firing_stand_ins(self, cons, r.condition, {}, head.containers);
                        for (const auto& [container, stand_in] : head.containers)
                            source.watched.emplace_back(container, edges(container));
                    }

                    // A predicate the firing substitutes with a term is not
                    // a plain one: the fact it derived has that term in its
                    // place.
                    const bool plain = predicate != 0 && !Zelph::is_var(predicate) && !var_in_closure(predicate) && head.containers.count(predicate) == 0;
                    if (plain) head.predicate = predicate;
                }
                std::vector<Node> parts;
                collect_conditions(self, nn_pred, closure_pred, r.condition, r.positive, r.negative, r.guards, r.closures, r.negated_closures, r.neural, &parts);
                for (const Node part : parts)
                    source.watched.emplace_back(part, edges(part));
                for (const Node condition : r.negative)
                    r.negative_patterns.push_back(build_pattern_info(self, condition, 1));
                for (const Node condition : r.positive)
                {
                    r.patterns.push_back(build_pattern_info(self, condition, 1));
                    ExplainRules::Shape shape;
                    adjacency_set       objects;
                    shape.subject  = self->parse_fact(condition, objects, rule);
                    shape.object   = objects.empty() ? 0 : *objects.begin();
                    shape.relation = parse_relation(condition);
                    std::unordered_set<Node> variables;
                    std::vector<Node>        history;
                    collect_variables(self, condition, variables, 0, history);
                    shape.variables.assign(variables.begin(), variables.end());
                    r.shapes.push_back(std::move(shape));
                }
                source.rule = fresh->rules.size();
                fresh->rules.push_back(std::move(r));
            }
            for (const RuleInForce& r : fresh->rules)
                for (const auto& head : r.heads)
                {
                    if (head.predicate != 0)
                        fresh->concluded.insert(head.predicate);
                    else
                        fresh->concludes_any = true;
                }
            auto watched = std::make_shared<ankerl::unordered_dense::set<Node>>();
            for (const auto& source : fresh->read_from)
            {
                watched->insert(source.node);
                for (const auto& [node, count] : source.watched)
                    watched->insert(node);
            }
            watch_removals(std::move(watched));
            _explain_rules = std::move(fresh);
        }
        const std::shared_ptr<const ExplainRules> rules = _explain_rules;

        const auto prepared = [&](ExplainContext& ctx, const std::size_t depth_limit)
        {
            ctx.z                 = self;
            ctx.engine            = this;
            ctx.nn_pred           = nn_pred;
            ctx.closure_pred      = closure_pred;
            ctx.closure_zero_plus = closure_zero_plus;
            ctx.root              = fact;
            ctx.max_depth         = depth_limit;
            ctx.rules             = rules->rules;
            ctx.in_force          = rules.get();
            ctx.unasserted        = unasserted_snapshot();
        };

        // Under a depth limit, the displayed tree represents the top of the
        // complete proof: the unrestricted search executes initially, after
        // which the renderer truncates the proof at the specified limit. Each
        // label and annotation within the tree corresponds exactly to what
        // the complete proof carries, and "[see above]" refers to the
        // identical proof object. The search confined by the limit, which was
        // the sole one, reuses the findings discovered at lower levels: a
        // fact established beneath the limit stood as
        // "asserted; no derivation found" at a higher level, a tree combined
        // results gathered at different depths, and a reference pointed
        // toward an expansion via the line's own ancestors.
        //
        // The search within the limit persists for proofs too large to find in
        // full: the search without it may perform up to
        // `default_explain_budget` units of work (see charge) before the root
        // achieves a clean proof, after which the annotation's own bound takes
        // effect. In a search large enough to matter, each unit consumes
        // between 0.25 us (the transitive closure of a ring) and 2.5 us
        // (proofs involving the arithmetic of the maths stack, and conditions
        // anchored at a hub, which read its adjacency and try the candidates
        // discovered there), on the machine where the budget was measured,
        // meaning 80 000 units halt the search for the complete proof after
        // 0.2 s. A hub where most facts carry the condition's predicate but
        // have the hub in the other role costs up to 4 us per unit, as
        // (Z bad h) does at the subject of a hundred thousand facts (h bad k),
        // and similarly for a condition that tries a hundred thousand
        // candidates in vain at each step; the search stops after no more than
        // a third of a second. Among the 1 008 explanations from the sessions
        // used to verify the documentation, the complete proof takes at most
        // 45 420 units -- the polynomial identity from the mathematics
        // overview, 0.09 s -- except for the Jacobian session of the paper,
        // whose arithmetic constitutes one component of 14 981 facts and may
        // require up to 373 000 units, 0.6 s; under a limit, these
        // explanations are searched within it. Of 40 explanations on a
        // materialized transitive P279 subgraph of Wikidata, half require
        // fewer than 35 000 units and the widest reaches 483 000, 0.45 s;
        // under a limit, 15 of 36 are searched within it. The annotation's
        // bound is layered atop the budget, so a depth-limited explanation
        // that finds its clean proof just within the budget might expend an
        // equal amount again in seeking a second one.
        ExplainContext ctx;
        prepared(ctx, 0);
        if (max_depth != 0)
        {
            ctx.budget     = explain_budget();
            ctx.work_limit = ctx.budget;
        }
        try
        {
            std::shared_ptr<ProofNode> proof = search(ctx, fact, 0).proof;
            _explain_counts                  = ctx.counts;
            _explain_counts.work             = ctx.work;
            return proof;
        }
        catch (const BudgetSpent&)
        {
        }

        ExplainContext limited;
        prepared(limited, max_depth);
        std::shared_ptr<ProofNode> proof = search(limited, fact, 0).proof;
        restore_levels(limited, proof);

        // Each search contributes to the total: a fact entered by both
        // searches is entered twice.
        _explain_counts          = limited.counts;
        _explain_counts.limited  = true;
        _explain_counts.work     = ctx.work + limited.work;
        _explain_counts.searches = ctx.counts.searches + limited.counts.searches;
        std::size_t facts        = limited.table.size();
        for (const auto& [node, entry] : ctx.table)
        {
            const auto  also  = limited.table.find(node);
            std::size_t total = entry.searches;
            if (also == limited.table.end())
                ++facts;
            else
                total += also->second.searches;
            _explain_counts.most = std::max(_explain_counts.most, total);
        }
        _explain_counts.facts = facts;
        return proof;
    }

    std::size_t Reasoning::explain_budget() const
    {
        return _explain_budget != 0 ? _explain_budget : default_explain_budget;
    }

    void Reasoning::set_explain_budget(const std::size_t searches) const
    {
        _explain_budget = searches;
    }

    Reasoning::ExplainCounts Reasoning::last_explain_counts() const
    {
        return _explain_counts;
    }
