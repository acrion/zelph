// Proof reconstruction: a single backward step executed at each level across
// the rule structures stored in the graph. For a target fact F:
//   1. enumerate the rules currently in force (refer to `RuleInForce`),
//   2. unify each rule's consequence template with F (operating in seed-mode
//      Unification: the candidate set consists precisely of {F}),
//   3. join the remaining positive conditions with asserted facts (employing
//      backtracking; conditions that become fully ground under the current
//      bindings are confirmed via pure hash lookup, all others via the
//      identical anchored Unification scan utilized in the forward pass),
//   4. check != guards and verify that no fact matches a NAF condition under
//      the join's bindings (variables local to it stay quantified),
//   5. search the positive premises the same way.
//
// Each fact undergoes a single search per explanation (tabling; under a
// depth limit a fact is searched again from higher up, as detailed in
// `prepare`). A premise whose search remains incomplete -- because it
// depends on the fact currently under construction -- leaves the
// instantiation PENDING. Facts that mutually depend on one another in this
// way constitute a strongly connected component within the search process,
// identified by Tarjan's algorithm while the search runs, and a component is
// resolved as a whole once every member has been searched: the least
// fixpoint over the instantiations constructed by the search establishes
// which members possess a derivation that does not rest on themselves
// (`complete_component`). Every derivation occurs in a finite number of
// forward steps, ensuring that such a derivation exists for each fact
// generated by the rules; a component where no member has such a derivation
// is settled via the SCC rule (`scc_leaves`). No tree places a fact beneath
// itself, at any depth (refer to `prepare` and `restore_levels`).
//
// The search keeps its own stack (`Frame`, `Join`). A proof's depth matches
// the chain of facts it relies on, and descending one call frame per level --
// the search, the enumeration of instantiations, the join, the premise, the
// search once more -- overflowed the thread's stack at roughly 2 000 levels
// and took the process down.
//
// Read-only by construction: resolve_pattern and check_fact are pure hash
// lookups, and Unification is used without a thread pool, so it only reads
// the graph. Nothing is created.

