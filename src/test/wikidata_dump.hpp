#pragma once

// Lines from a Wikidata dump generated by a test, concerning the ways in
// which an import transforms labels.

#include "interactive.hpp"
#include "network/reasoning.hpp"

#include <filesystem>
#include <fstream>
#include <optional>
#include <string>
#include <vector>

namespace zelph::test::wikidata_dump
{
    // A .json load writes a .bin cache next to the source; a second load
    // would read that cache instead of re-importing, so both go away.
    inline void remove_dump(const std::filesystem::path& dump)
    {
        std::filesystem::path cache = dump;
        cache.replace_extension(".bin");
        std::filesystem::remove(cache);
        std::filesystem::remove(dump);
    }

    // A single entry within the "labels", "descriptions", or "aliases"
    // object of a dump's data.
    inline std::string text(const std::string& lang, const std::string& value)
    {
        return "\"" + lang + "\":{\"language\":\"" + lang + "\",\"value\":\"" + value + "\"}";
    }

    // A single claim within a dump line: `property` having the item
    // `object` as its assigned value, in the shape the importer reads.
    inline std::string claim(const std::string& property, const std::string& object)
    {
        return "\"" + property + "\":[{\"mainsnak\":{\"snaktype\":\"value\",\"property\":\"" + property
             + "\",\"datavalue\":{\"value\":{\"entity-type\":\"item\",\"numeric-id\":" + object.substr(1)
             + ",\"id\":\"" + object + "\"},\"type\":\"wikibase-entityid\"},\"datatype\":\"wikibase-item\"},"
                                       "\"type\":\"statement\",\"id\":\"S$1\",\"rank\":\"normal\"}]";
    }

    // A dump line for an item or a property, shaped like the real dump: the
    // identifier first, followed by the labels object (the comma-separated
    // values within `labels`), the claims (entries created via `claim`),
    // descriptions, and aliases.
    inline std::string entity(const std::string& id,
                              const std::string& labels,
                              const std::string& claims       = "",
                              const std::string& descriptions = "",
                              const std::string& aliases      = "")
    {
        const std::string type = id[0] == 'P' ? "\"type\":\"property\",\"datatype\":\"wikibase-item\"" : "\"type\":\"item\"";
        return "{" + type + ",\"id\":\"" + id + "\",\"labels\":{" + labels + "},\"descriptions\":{" + descriptions
             + "},\"aliases\":{" + aliases + "},\"claims\":{" + claims + "},\"sitelinks\":{}}";
    }

    // A dump of the specified lines within the temporary directory,
    // excluding the .bin cache that an earlier import with the same name
    // created adjacent to it.
    inline std::filesystem::path write_lines(const std::string& name, const std::vector<std::string>& lines)
    {
        const auto path = std::filesystem::temp_directory_path() / (name + ".json");
        remove_dump(path);

        std::ofstream out(path, std::ios::binary);
        out << "[\n";
        for (size_t i = 0; i < lines.size(); ++i)
            out << lines[i] << (i + 1 < lines.size() ? ",\n" : "\n");
        out << "]\n";
        return path;
    }

    // The node named `id` in the language `wikidata`; every entity that
    // has been imported possesses such a name.
    inline zelph::network::Node entity_node(const zelph::console::Interactive& interactive, const std::string& id)
    {
        return interactive.graph()->get_node(id, "wikidata");
    }

    // The entity whose `en` name is `label`, as `.lang en` resolves it.
    inline std::string holder_of(const zelph::console::Interactive& interactive, const std::string& label)
    {
        const zelph::network::Node node = interactive.graph()->get_node(label, "en");
        return node == 0 ? "" : interactive.graph()->get_name(node, "wikidata", false);
    }

    inline std::string en_name_of(const zelph::console::Interactive& interactive, const std::string& id)
    {
        return interactive.graph()->get_name(entity_node(interactive, id), "en", false);
    }

    // The identifiers from Wikidata associated with the nodes listed by
    // Zelph::nodes_named, in the sequence they appear.
    inline std::vector<std::string> ids_of(const zelph::console::Interactive& interactive, const std::optional<std::vector<zelph::network::Node>>& nodes)
    {
        if (!nodes) return {"(incomplete)"};
        std::vector<std::string> ids;
        for (const zelph::network::Node node : *nodes)
            ids.push_back(interactive.graph()->get_name(node, "wikidata", false));
        return ids;
    }
}
